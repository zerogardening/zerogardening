/* 05c-입고저장 — 입고 탭 진입점과 저장 (설계 §8-1) */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  var u = ZG.ui, 만들기 = u.만들기;
  var 내 = ZG.입고내부, 상태 = 내.상태, 참조 = ZG.입고내부.참조;

  function 그리기(뿌리) {
    참조.뿌리 = 뿌리;
    u.비우기(뿌리);
    참조.오류 = {};
    if (u.폰인가()) {
      if (상태.수정id) { ZG.입고수정.폰상세그리기(뿌리); return; }
    } else {
      상태.수정id = null;      // PC 폭에서는 시트로 고친다
    }
    if (!상태.입고일) 상태.입고일 = u.오늘문자();
    if (!상태.입고업체) 상태.입고업체 = ZG.저장소.설정읽기().마지막입고업체 || '';

    var 조각 = u.폰인가() ? ZG.입고배치.폰배치() : ZG.입고배치.PC배치();
    조각.forEach(function (c) { 뿌리.appendChild(c); });
    내.금액갱신();
    내.코드갱신();
  }

  function 요약() {
    var 범위 = [u.오늘문자(), u.오늘문자()];
    var 오늘것 = ZG.저장소.읽기(ZG.저장소.키.입고).filter(function (r) {
      return r.입고일 >= 범위[0] && r.입고일 <= 범위[1];
    });
    var 주 = 오늘것.reduce(function (a, r) { return a + (Number(r.수량) || 0); }, 0);
    return {
      왼: 상태.입고일 + (상태.입고업체 ? ' · ' + 상태.입고업체 : ''),
      오: '오늘 <b>' + 오늘것.length + '</b>건 · <b>' + u.콤마(주) + '</b>주'
    };
  }

  /* 토스트 · 흔들림에 더해 그 칸 바로 아래 빨간 줄까지 (설계 §16-4) */
  function 알림(이름, 글) {
    u.토스트(글);
    내.오류보이기(이름, 글);
    var 칸 = 참조[이름];
    if (칸) { u.흔들기(칸); if (칸.focus) 칸.focus(); }
    else if (이름 === '규격') u.흔들기(참조.규격오류);
    return false;
  }

  function 검사() {
    내.오류전부지우기();
    if (!상태.입고일) return 알림('입고일', '입고일자를 넣어주세요');
    if (!String(상태.입고업체).trim()) return 알림('입고업체', '입고업체를 넣어주세요');
    if (!String(상태.유통명).trim()) return 알림('유통명', '유통명을 넣어주세요');
    if (상태.규격cm == null) return 알림('규격', '규격을 골라주세요');
    var 수량 = u.숫자(상태.수량);
    if (!(수량 >= 1) || 수량 !== Math.floor(수량)) return 알림('수량', '수량은 1 이상 정수로 넣어주세요');
    var 단가 = u.숫자(상태.매입단가);
    if (!(단가 >= 0)) return 알림('매입단가', '매입단가를 넣어주세요');
    if (!String(상태.학명).trim()) return 알림('학명', '학명을 넣어야 품목코드가 만들어집니다');

    var 결과 = 상태.코드결과;
    if (결과 && 결과.상태 === '확인필요' && !상태.고른갈래) {
      u.토스트('같은 식물인지 먼저 골라주세요');
      if (참조.경고칸) 참조.경고칸.scrollIntoView({ block: 'center', behavior: u.움직임끔() ? 'auto' : 'smooth' });
      return false;
    }
    if (!상태.코드) { 알림('품목코드를 만들지 못했습니다 — 학명과 규격을 확인해 주세요', 참조.학명); return false; }
    return true;
  }

  function 품목반영(코드) {
    var 키 = ZG.저장소.키;
    var 품목 = ZG.저장소.읽기(키.품목);
    var 있는것 = 품목.find(function (p) { return p.품목코드 === 코드; });
    var 이제 = Date.now();

    var 특성 = 참조.특성 ? 참조.특성.읽기() : null;

    if (있는것) {
      // 유통명 · 학명은 건드리지 않는다 — 재고 수정에서만 고친다
      var 바꿀것 = { 매입단가: u.숫자(상태.매입단가), 과세구분: 상태.과세구분, 수정일시: 이제 };
      if (특성) 바꿀것.특성 = 특성;      // 안 적었으면 이미 있는 특성을 지우지 않는다
      ZG.저장소.바꾸기(키.품목, 코드, 바꿀것);
      return 있는것;
    }
    var 새것 = {
      품목코드: 코드,
      접두: 코드.slice(0, 5),
      학명3: 코드.slice(0, 3),
      일련번호: 코드.slice(3, 5),
      규격cm: 상태.규격cm,
      규격: 상태.규격cm + 'cm 포트',
      유통명: String(상태.유통명).trim(),
      학명: String(상태.학명).trim(),
      학명키: ZG.품목코드.학명키(상태.학명),
      매입단가: u.숫자(상태.매입단가),
      과세구분: 상태.과세구분,
      상태: '판매중',
      특성: 특성,
      등록일시: 이제,
      수정일시: 이제
    };
    ZG.저장소.덧붙이기(키.품목, 새것);
    return 새것;
  }

  /* 새 업체는 되돌리기 번거로워서 한 번 묻는다 (설계 §16-2). 입고 수정(05e)도 이걸 쓴다 */
  function 업체확인(이름, 그때) {
    var 있나 = ZG.저장소.읽기(ZG.저장소.키.업체).some(function (c) { return c.이름 === 이름; });
    if (있나) { 그때(true); return; }
    u.확인({
      제목: '처음 보는 업체입니다',
      본문: '<b>' + u.안전(이름) + '</b> 를 업체 목록에 새로 넣을까요?<br>이름이 잘못 적혔다면 취소하고 고쳐주세요.',
      확인글: '새 업체로 등록'
    }, 그때);
  }

  function 업체반영(이름) {
    var 키 = ZG.저장소.키;
    var 업체 = ZG.저장소.읽기(키.업체);
    var 있는것 = 업체.find(function (c) { return c.이름 === 이름; });
    if (있는것) ZG.저장소.바꾸기(키.업체, 있는것.id, { 마지막사용: Date.now() });
    else ZG.저장소.덧붙이기(키.업체, {
      id: 'co_' + Date.now().toString(36) + '_' + Math.random().toString(36).slice(2, 7),
      이름: 이름, 구분: '공급업체', 마지막사용: Date.now()
    });
  }

  function 폼비우기(전부) {
    상태.유통명 = ''; 상태.학명 = ''; 상태.규격cm = null; 상태.직접규격 = '';
    상태.수량 = ''; 상태.매입단가 = ''; 상태.과세구분 = '면세'; 상태.메모 = '';
    상태.코드 = ''; 상태.코드결과 = null; 상태.고른갈래 = null; 상태.기존품목 = null;
    if (전부) { 상태.입고업체 = ''; 상태.입고일 = u.오늘문자(); }

    ['유통명', '학명', '수량', '매입단가', '메모'].forEach(function (이름) {
      if (참조[이름]) 참조[이름].value = '';
    });
    if (참조.특성) 참조.특성.비우기();
    if (참조.입고업체) 참조.입고업체.value = 상태.입고업체;
    if (참조.입고일) 참조.입고일.value = 상태.입고일;
    내.규격표시(); 내.과세표시(); 내.금액갱신(); 내.코드갱신();
    if (참조.경고칸) u.비우기(참조.경고칸);
  }

  function 저장(뒤에) {
    if (!검사()) return;
    업체확인(String(상태.입고업체).trim(), function (계속할까) {
      if (계속할까) 저장진행(뒤에);
    });
  }

  function 저장진행(뒤에) {
    var 키 = ZG.저장소.키;
    var 코드 = 상태.코드;
    var 품목 = 품목반영(코드);

    var 기록 = {
      id: 'rc_' + Date.now().toString(36) + '_' + Math.random().toString(36).slice(2, 7),
      입고일: 상태.입고일,
      입고업체: String(상태.입고업체).trim(),
      품목코드: 코드,
      유통명: 품목.유통명,
      학명: 품목.학명,
      규격: 상태.규격cm + 'cm 포트',
      수량: u.숫자(상태.수량),
      매입단가: u.숫자(상태.매입단가),
      과세구분: 상태.과세구분,
      메모: String(상태.메모 || '').trim(),
      등록일시: Date.now()
    };
    ZG.저장소.덧붙이기(키.입고, 기록);
    업체반영(기록.입고업체);
    ZG.저장소.설정쓰기({ 마지막입고업체: 기록.입고업체 });

    u.토스트('저장했습니다 — ' + 코드 + ' · ' + u.콤마(기록.수량) + '주');
    상태.방금저장 = 기록.id;
    상태.기간 = '오늘'; 상태.직접범위 = null;

    폼비우기(뒤에 === '끝내기');
    ZG.입고내역.내역다시();
    ZG.앱 && ZG.앱.요약다시();
    if (뒤에 !== '끝내기' && 참조.유통명) 참조.유통명.focus();
  }

  function 단추(무엇) {
    if (무엇 === '비우기') {
      var 찼나 = 상태.유통명 || 상태.학명 || 상태.수량 || 상태.매입단가;
      if (찼나 && !window.confirm('넣던 것을 지울까요?')) return;
      폼비우기(false);
      return;
    }
    저장(무엇);
  }

  /* 재고 화면의 「입고 등록」 버튼이 이 품목으로 채워 달라고 부른다 */
  function 채우기(품목) {
    상태.유통명 = 품목.유통명; 상태.학명 = 품목.학명;
    상태.규격cm = 품목.규격cm; 상태.매입단가 = String(품목.매입단가); 상태.과세구분 = 품목.과세구분;
    상태.수량 = '';
  }

  ZG.입고 = {
    그리기: 그리기, 단추: 단추, 요약: 요약, 채우기: 채우기,
    업체확인: 업체확인, 업체반영: 업체반영   // 입고 수정(05e)이 같은 규칙을 쓴다
  };
})(window.ZG);
