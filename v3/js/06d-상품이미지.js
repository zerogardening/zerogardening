/* 06d-상품이미지 — 「상품」 화면 세 번째 탭. 상세페이지·대표이미지를 여기서 고친다.
   05(입고) · 06a~c(재고) 와 같은 갈래로, 07-앱이 부르는 탭 모듈이다.

   🔴 자료를 받아오지 않는다 — 맥에서 도는 편집기(상품/_도구/편집.py) 창만 얹는다.
      통합관리는 https 이고 편집기는 http://127.0.0.1 이다. 브라우저는 127.0.0.1 을
      안전한 자리로 쳐서 창은 막지 않지만, 자료를 받아오려 들면 사설망 검사에 걸릴
      여지가 있다. 상품 고르기·자동완성·저장은 전부 편집기 안(같은 자리)에서 돈다.

   🔴 편집기가 꺼져 있으면 창이 빈다. 그때는 맥 터미널에 「상품이미지」 한 낱말이다.
      (자동 실행은 아직 안 붙였다 — 2026-08-11) */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  var u = ZG.ui, 만들기 = u.만들기;
  var 편집기 = 'http://127.0.0.1:8765/';

  function 머리() {
    return { 제목: '상품 이미지', 왼: '상세페이지 · 대표이미지', 오: '' };
  }

  function 그리기(본문) {
    u.비우기(본문);

    /* 폰에서는 안 연다. 사진을 보며 글자를 고치는 자리라 좁으면 못 쓴다 */
    if (u.폰인가()) {
      var 말 = 만들기('div', { class: 'img-덧 img-폰' });
      말.innerHTML = '이 탭은 <b>PC에서</b> 쓰십니다.<br>' +
                     '사진을 보면서 글자를 고치는 자리라 폰에서는 좁습니다.';
      본문.appendChild(말);
      return;
    }

    var 덧 = 만들기('div', { class: 'img-덧' });
    덧.innerHTML = '아래가 비어 있으면 편집기가 꺼져 있는 것입니다 — ' +
                   '맥 터미널에 <b>상품이미지</b> 한 낱말을 치시고 이 탭을 다시 누르십시오. ' +
                   '🔴 <b>고치던 것은 저장하고 탭을 옮기십시오</b> — 탭을 바꾸면 창이 새로 뜹니다.';

    var 틀 = 만들기('div', { class: 'img-틀' }, [
      덧,
      만들기('iframe', { class: 'img-창', src: 편집기, title: '상품 이미지 편집기' })
    ]);
    본문.appendChild(틀);
  }

  ZG.상품이미지 = { 그리기: 그리기, 머리: 머리 };
})(window.ZG);
