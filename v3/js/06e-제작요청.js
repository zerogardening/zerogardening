/* 06e-제작요청 — 재고 탭에서 고른 품목을 상품팀 일감으로 넘긴다 (13단계)
   두 가지다 —
     상세페이지 : 맥에서 `상품/품목/{품목}/입력.md` 가 만들어지고 상품팀이 착수한다
     식물정보   : 최대높이·너비·내한성·물주기·햇빛·개화기·관리특이사항 7칸을 채워 되돌려 준다

   🔴 요청만 쌓는다. 제작을 여기서 시작시키지 않는다 —
      받는 쪽은 맥의 `통합관리/도구/제작요청받기.py` 이고, 사람이 부른다.
   서버로는 기존 갈래(01c-보내기 → v3_제작요청)를 그대로 탄다. 표 이름 하나만 늘렸다. */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  var u = ZG.ui;
  var 종류들 = { 상세페이지: '상세페이지', 식물정보: '식물정보' };

  function 살아있는것() {
    return ZG.저장소.읽기(ZG.저장소.키.제작요청).filter(function (r) {
      return !r.삭제됨 && r.상태 !== '끝';
    });
  }

  /* 품목코드 → { 상세페이지: '대기'|'받음', 식물정보: … }. 목록을 그릴 때 한 번만 만든다 */
  function 현황() {
    var 표 = {};
    살아있는것().forEach(function (r) {
      var 것 = 표[r.품목코드] || (표[r.품목코드] = {});
      /* 같은 품목·같은 종류가 둘이면 더 진행된 쪽을 보인다 */
      if (것[r.종류] !== '받음') 것[r.종류] = r.상태;
    });
    return 표;
  }

  function 칩들(현, 코드) {
    var 것 = 현 && 현[코드];
    if (!것) return '';
    return Object.keys(종류들).map(function (종) {
      if (!것[종]) return '';
      var 짧게 = 종 === '상세페이지' ? '상세' : '정보';
      return '<span class="chip 요청' + (것[종] === '받음' ? ' 진행' : '') + '">' +
             짧게 + (것[종] === '받음' ? ' 진행중' : ' 요청') + '</span>';
    }).join('');
  }

  function 요청하기(종류, 뒤에) {
    var 코드들 = ZG.재고목록.고른것들();
    if (!코드들.length) { u.토스트('품목을 먼저 골라주세요'); return; }

    var 품목 = ZG.저장소.품목들();
    var 현 = 현황();
    var 새것 = [], 이미 = 0, 없음 = 0;
    코드들.forEach(function (c) {
      if (현[c] && 현[c][종류]) { 이미++; return; }
      var p = 품목.find(function (x) { return x.품목코드 === c; });
      if (!p) { 없음++; return; }
      새것.push(p);
    });

    if (!새것.length) {
      u.토스트(이미 ? '고른 ' + 이미 + '종은 이미 요청했습니다' : '요청할 품목이 없습니다');
      return;
    }

    var 이름 = 새것.map(function (p) { return p.유통명; });
    var 본문 = '<b>' + u.안전(이름.slice(0, 5).join(' · ')) +
      (이름.length > 5 ? ' 외 ' + (이름.length - 5) + '종' : '') + '</b>';
    본문 += 종류 === '상세페이지'
      ? '<br><br>상품팀 착수 파일(<b>입력.md</b>)이 만들어집니다.<br>' +
        '제작이 바로 시작되지는 않습니다 — 맥에서 받아 가야 합니다.'
      : '<br><br>최대높이 · 너비 · 내한성 · 물주기 · 햇빛 · 개화기 · 관리 특이사항을 조사해 채워 돌려줍니다.<br>' +
        '<b>이미 적어 두신 칸은 덮어쓰지 않습니다.</b>';
    if (이미) 본문 += '<br><br>이미 요청한 ' + 이미 + '종은 뺐습니다.';
    if (없음) 본문 += '<br>못 찾은 품목 ' + 없음 + '종은 뺐습니다.';

    u.확인({ 제목: 새것.length + '종 ' + 종류 + '를 요청할까요?', 본문: 본문, 확인글: '요청' }, function (예) {
      if (!예) return;
      var 이제 = Date.now();
      새것.forEach(function (p, i) {
        ZG.저장소.덧붙이기(ZG.저장소.키.제작요청, {
          id: 'pr_' + 이제.toString(36) + '_' + i + '_' + Math.random().toString(36).slice(2, 7),
          품목코드: p.품목코드,
          종류: 종류,
          유통명: p.유통명,
          학명: p.학명,
          규격cm: p.규격cm,
          상태: '대기',
          요청일시: 이제
        });
      });
      ZG.재고목록.선택비우기();
      ZG.재고목록.상태.선택모드 = false;
      ZG.앱.다시그리기();
      if (뒤에) 뒤에();
      u.토스트(새것.length + '종 요청했습니다' + (이미 ? ' · ' + 이미 + '종은 이미 요청됨' : ''));
    });
  }

  ZG.제작요청 = { 종류들: 종류들, 현황: 현황, 칩들: 칩들, 요청하기: 요청하기 };
})(window.ZG);
