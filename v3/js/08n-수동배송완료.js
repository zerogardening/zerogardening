/* 08n-수동배송완료 — ③ 로젠 파일 없이 고른 건을 배송완료로 · 같은 자리에서 되돌리기 (9단계 설계 §5)
   🔴 넘길 줄을 고르는 관문은 08f.넘길줄만 하나뿐이다. 여기서 우회하지 않는다.
   🔴 되돌리기는 `출처==='주문'` 출고만 지운다 — 서비스 출고를 지우면 사은품 재고가 는다. */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  var u = ZG.ui;
  function B() { return ZG.배송완료; }

  function 줄모으기(건들) {
    return (건들 || []).reduce(function (a, g) { return a.concat(g.줄들 || []); }, []);
  }

  /* 5-1·5-2 가 단추를 고를 때 쓴다 */
  function 상태보기(g) {
    if (!g) return { 나감: 0, 넘길수있는: 0 };
    var 색인 = B().색인만들기();
    return {
      나감: B().주문출고찾기(g.줄들 || []).length,
      넘길수있는: B().넘길줄만(g.줄들 || [], 색인).넘길.length
    };
  }

  /* ══ ✋ 배송완료로 넘기기 ══ */

  /* 그다음(했나) 는 취소·헛걸음까지 포함해 **언제나** 불린다 — 부르는 쪽이 Esc 주인을 되찾아야 한다
     (04-공통UI 의 탈출 자리는 하나뿐이라, 확인창을 띄우기 전에 푼 것을 반드시 다시 걸어야 한다) */
  function 넘기기(건들, 그다음) {
    function 끝(했나) { if (그다음) 그다음(했나); }
    건들 = 건들 || [];
    if (!건들.length) { u.토스트('먼저 주문표에서 건을 고르세요.'); 끝(false); return; }

    var 색인 = B().색인만들기();
    var 넘길 = [], 줄글 = [];
    건들.forEach(function (g) {
      var 갈래 = B().넘길줄만(g.줄들 || [], 색인);
      if (!갈래.넘길.length) return;                 // 서비스·이미나감·품목미확인·수량0은 여기서 빠진다
      넘길 = 넘길.concat(갈래.넘길);
      줄글.push(u.안전((g.수령인 || '(이름 없음)') + ' · ' + B().차감글(갈래.넘길)));
    });
    if (!넘길.length) { u.토스트('이미 나갔거나 품목코드가 없어 넘길 줄이 없습니다.'); 끝(false); return; }

    var 본문 = 줄글.slice(0, 5).join('<br>') +
      (줄글.length > 5 ? '<br>외 ' + (줄글.length - 5) + '건' : '') +
      '<br>─ <b>재고가 그만큼 줄어듭니다.</b> 잘못 눌렀으면 「↩ 배송완료 되돌리기」로 되돌릴 수 있습니다.' +
      /* 🔴 로젠 송장이 없으므로 카페24에는 아무 것도 안 보낸다 */
      '<br>카페24·심폴에는 발송처리되지 않습니다 — 그쪽은 직접 처리하세요';

    u.확인({
      제목: 줄글.length + '건을 배송완료로 넘길까요',
      본문: 본문, 확인글: '배송완료로 넘기기', 위험: true
    }, function (예) {
      if (!예) { 끝(false); return; }
      var 만든 = B().출고넣기(넘길, u.오늘문자(), 색인, { 수동: true, 배치: B().새배치() });
      u.토스트('출고 ' + 만든.length + '건을 기록했습니다 — 재고 ' + B().코드모음(넘길).length + '품목 차감.');
      끝(true);
    });
  }

  /* ══ ↩ 배송완료 되돌리기 ══ */

  function 되돌리기(건들, 그다음) {
    function 끝(했나) { if (그다음) 그다음(했나); }
    건들 = 건들 || [];
    var 줄들 = 줄모으기(건들);
    var 출고id들 = B().주문출고찾기(줄들);
    if (!출고id들.length) { u.토스트('되돌릴 출고가 없습니다.'); 끝(false); return; }

    var 카페24감 = 줄들.some(function (r) { return r.카페24상태 && r.카페24상태 !== '배송준비중'; });
    u.확인({
      제목: '배송완료를 되돌릴까요',
      본문: '출고 <b>' + 출고id들.length + '건</b>을 지우고 재고를 원래대로 돌립니다.' +
        (카페24감 ? '<br>이 건은 카페24에서 이미 발송처리됐습니다 — 카페24 쪽은 되돌아가지 않습니다' : ''),
      확인글: '되돌리기', 위험: true
    }, function (예) {
      if (!예) { 끝(false); return; }
      var 센수 = B().출고되돌리기(출고id들);
      /* 🔴 `카페24상태`는 손대지 않는다 — 카페24가 진실이다 */
      u.토스트('출고 ' + 센수 + '건을 되돌렸습니다 — 재고 원래대로.');
      끝(true);
    });
  }

  ZG.수동배송완료 = { 넘기기: 넘기기, 되돌리기: 되돌리기, 상태보기: 상태보기 };
})(window.ZG);
