/* 06k-마켓품절 — 재고 상태(판매중·품절)를 카페24·심폴에 밀어 넣는다 (2026-09-18 우람님).
   부르는 곳은 06c-재고수정의 `저장()` 하나다. 화면은 안 그린다 — 팝업만 띄운다.

   🔴 **여기서 카페24·심폴을 직접 부르지 않는다.** 열쇠가 브라우저에 들어가면 안 된다.
      Edge Function `market-soldout` 이 대신 부른다 (통합관리/도구/edge-마켓품절).
   🔴 **오픈마켓(쿠팡·스마트스토어…)은 아직 안 나간다** — 마켓플러스를 따로 밀어야 하는데
      그 길이 아직 안 뚫렸다(2026-09-18). 그래서 팝업이 그 사실을 사람에게 그대로 알린다.
      🔴 조용히 빼먹으면 카페24만 품절되고 쿠팡은 계속 팔린다. 반드시 보여준다. */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  var u = ZG.ui;

  function 클라이언트() {
    var 서 = ZG.서버;
    return (서 && 서.켜짐 && 서.클라이언트) ? 서.클라이언트 : null;
  }

  function 이름표(품목) { return 품목.유통명 || 품목.품목코드; }

  /* 한 줄로 읽히게 — 「카페24 ✅」 「심폴 ❌ 짝이 없습니다」 */
  function 줄(누구, 것) {
    if (!것) return 누구 + ' — 답이 없습니다';
    if (것.됨) return 누구 + ' ✅' + (것.사유 ? ' (' + 것.사유 + ')' : '');
    return 누구 + ' ❌ ' + (것.사유 || '까닭을 모릅니다');
  }

  /* 결과 알리기. 둘 다 됐으면 토스트로 스쳐 보내고, 하나라도 막혔으면 붙잡아 보여준다 */
  function 알리기(이름, 품절, 답) {
    var 카 = 답.카페24;
    if (카 && 카.됨) {
      u.토스트(이름 + ' — 자사몰 ' + (품절 ? '품절했습니다' : '다시 팝니다') + ' · 심폴 · 오픈마켓은 맥이 이어서');
      return;
    }
    /* 🔴 자사몰이 막혀도 심폴·오픈마켓 지시는 이미 쌓아 뒀다 — 맥이 그것만은 해낸다 */
    u.확인({
      제목: 이름 + ' — 자사몰이 막혔습니다',
      본문: u.안전(줄('카페24', 카)) + '<br>심폴 · 오픈마켓 ⏳ 맥이 이어서 합니다' +
            '<br><br>v3 에는 ' + (품절 ? '품절' : '판매중') + ' 로 적혀 있습니다.',
      확인글: '알겠습니다', 취소글: '닫기'
    }, function () {});
  }

  /* 물어보고 → 예면 그때(true) 로 v3 에 먼저 적게 하고 → 마켓에 민다.
     🔴 취소하시면 그때(false) — **v3 상태도 안 바꾼다.** 마켓과 v3 가 어긋나는 게 제일 나쁘다. */
  function 물어보고밀기(품목, 품절, 그때) {
    var 이름 = 이름표(품목);
    var 클 = 클라이언트();

    if (!클) {
      u.확인({
        제목: 이름 + ' — 서버가 꺼져 있습니다',
        본문: '마켓에는 못 보냅니다. <b>v3 에만</b> ' + (품절 ? '품절' : '판매중') + ' 로 적을까요?',
        확인글: 'v3 에만 적는다'
      }, 그때);
      return;
    }

    u.확인({
      /* 🔴 묻는 말이 아니라 **무슨 일이 일어나는지** 적는다 (우람님 2026-09-18).
         단추가 이미 지금 상태를 보여주니, 팝업은 누르면 뭐가 되는지만 말하면 된다. */
      제목: 이름 + (품절 ? ' — 모든 마켓에서 품절처리 합니다' : ' — 다시 판매가 재개됩니다'),
      본문: '자사몰을 <b>' + (품절 ? '품절</b>로' : '판매중</b>으로') + ' 바로 바꿉니다.<br>' +
            '심폴 · 오픈마켓은 <b>맥이 이어서</b> 합니다 (1~2분).',
      확인글: 품절 ? '품절한다' : '다시 판다',
      위험: 품절
    }, function (예) {
      if (!예) { 그때(false); return; }
      그때(true);                    // v3 에 먼저 적는다 — 마켓이 느려도 화면은 바로 닫힌다
      밀기(품목, 품절);
    });
  }

  function 밀기(품목, 품절) {
    var 이름 = 이름표(품목), 클 = 클라이언트();
    if (!클) return;
    u.토스트(이름 + ' — 마켓에 보내는 중…');
    맥에넘기기(품목, 품절).catch(function () { u.토스트('오픈마켓 지시를 못 쌓았습니다'); });
    Promise.resolve(클.functions.invoke('market-soldout', {
      body: { 품목코드: 품목.품목코드, 품절: !!품절 }
    })).then(function (답) {
      if (답 && 답.error) throw 답.error;
      var d = (답 && 답.data) || {};
      if (!d.ok) throw new Error(d.오류 || '함수가 거절했습니다');
      알리기(이름, 품절, d);
    }).catch(function (e) {
      u.확인({
        제목: 이름 + ' — 마켓에 못 보냈습니다',
        본문: u.안전(String((e && e.message) || e)) +
              '<br><br>v3 에는 ' + (품절 ? '품절' : '판매중') + ' 로 적혀 있습니다. 마켓은 손으로 봐 주세요.',
        확인글: '알겠습니다', 취소글: '닫기'
      }, function () {});
    });
  }

  /* 오픈마켓(쿠팡·스마트스토어…)은 브라우저가 못 닿는다 — 마켓플러스는 로그인·JS 화면이다.
     🔴 그래서 `v3_지시` 에 한 줄만 쌓고 **맥이 집어서** `상품/_도구/마켓플러스품절.py` 를 돌린다
        (06j-결과화면.js 의 「카페24 올리기」와 같은 길이다).
     🔴 **맥이 꺼져 있으면 안 나간다.** 그래서 팝업이 마켓플러스를 따로 「⏳ 맥이 이어서」로 알린다.
     🔴 실패해도 카페24·심폴 결과는 그대로 보여준다 — 한쪽만 되는 게 둘 다 안 되는 것보다 낫다. */
  function 맥에넘기기(품목, 품절) {
    var 클 = 클라이언트();
    if (!클) return Promise.resolve();
    var 이제 = Date.now();
    var 이름 = 이름표(품목);
    var 줄하나 = {
      누가: '시스템', 보낸때: 이제, 상태: '대기',
      갈래: 품절 ? '마켓품절' : '마켓판매',
      품목코드: 품목.품목코드, 폴더: 이름,
      글: 이름 + ' — 오픈마켓을 ' + (품절 ? '품절' : '다시 판매') + ' 처리합니다.'
    };
    return Promise.resolve(클.from('v3_지시').upsert([{
      id: 이제 + '-' + String(품목.품목코드).slice(0, 8), 삭제됨: false, 내용: 줄하나
    }], { onConflict: 'id' })).then(function (답) {
      if (답 && 답.error) throw 답.error;
    });
  }

  /* ── 카드·표에서 바로 누르는 단추 (우람님 2026-09-18) ──
     🔴 단추는 **지금 상태**를 보여준다 — 판매중이면 🟢초록 「판매중」 · 품절이면 🔴빨강 「품절」.
        누르면 그 자리에서 **반대로 바꿀지** 묻는다(판매중을 누르면 품절할까요?).
        동작 이름(「품절처리」)을 적어 뒀더니 지금 뭐가 팔리는지 한눈에 안 보였다 (우람님 2026-09-18).
     🔴 카드(.ph-card)가 그 자체로 button 이라 눌림이 위로 새면 상세가 열린다 —
        `stopPropagation()` 으로 막는다 (06g 의 `뺌단추` 와 같은 수). */
  function 단추(품목, 그린뒤) {
    var 품절인가 = 품목.상태 === '품절';
    var b = u.만들기('button', {
      type: 'button',
      class: 'btn sm 품절단추 ' + (품절인가 ? 'warn' : 'main'),
      text: 품절인가 ? '품절' : '판매중'
    });
    b.addEventListener('click', function (e) {
      e.stopPropagation();
      if (b.disabled) return;
      바꾸기(품목, !품절인가, b, 그린뒤);
    });
    return b;
  }

  /* 눌렀을 때 — 물어보고, 예면 v3 에 적고 마켓으로 민다 */
  function 바꾸기(품목, 품절로, b, 그린뒤) {
    물어보고밀기(품목, 품절로, function (예) {
      if (!예) return;
      ZG.저장소.바꾸기(ZG.저장소.키.품목, 품목.품목코드,
                      { 상태: 품절로 ? '품절' : '판매중', 수정일시: Date.now() });
      품목.상태 = 품절로 ? '품절' : '판매중';       /* 손에 든 것도 맞춰 둔다 */
      b.textContent = 품절로 ? '품절' : '판매중';
      b.classList.toggle('warn', 품절로);
      b.classList.toggle('main', !품절로);
      if (그린뒤) 그린뒤();
    });
  }

  ZG.마켓품절 = { 물어보고밀기: 물어보고밀기, 밀기: 밀기, 맥에넘기기: 맥에넘기기, 단추: 단추 };
})(window.ZG);
