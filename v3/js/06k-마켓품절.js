/* 06k-마켓품절 — 재고 상태(판매중·품절)를 카페24·심폴에 밀어 넣는다 (2026-09-18 우람님).
   부르는 곳은 06c-재고수정의 `저장()` 하나다. 화면은 안 그린다 — 팝업만 띄운다.

   🔴 **여기서 카페24·심폴을 직접 부르지 않는다.** 열쇠가 브라우저에 들어가면 안 된다.
      Edge Function `market-soldout` 이 대신 부른다 (통합관리/도구/edge-마켓품절).
   🔴 **오픈마켓(쿠팡·스마트스토어…)은 아직 안 나간다** — 마켓플러스를 따로 밀어야 하는데
      그 길이 아직 안 뚫렸다(2026-09-18). 그래서 팝업이 그 사실을 사람에게 그대로 알린다.
      🔴 조용히 빼먹으면 카페24만 품절되고 쿠팡은 계속 팔린다. 반드시 보여준다. */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  var u = ZG.ui;

  function 클라이언트() {
    var 서 = ZG.서버;
    return (서 && 서.켜짐 && 서.클라이언트) ? 서.클라이언트 : null;
  }

  function 이름표(품목) { return 품목.유통명 || 품목.품목코드; }

  /* 한 줄로 읽히게 — 「카페24 ✅」 「심폴 ❌ 짝이 없습니다」 */
  function 줄(누구, 것) {
    if (!것) return 누구 + ' — 답이 없습니다';
    if (것.됨) return 누구 + ' ✅' + (것.사유 ? ' (' + 것.사유 + ')' : '');
    return 누구 + ' ❌ ' + (것.사유 || '까닭을 모릅니다');
  }

  /* 결과 알리기. 둘 다 됐으면 토스트로 스쳐 보내고, 하나라도 막혔으면 붙잡아 보여준다 */
  function 알리기(이름, 품절, 답) {
    var 카 = 답.카페24, 심 = 답.심폴;
    var 다됨 = 카 && 카.됨 && 심 && 심.됨;
    if (다됨) { u.토스트(이름 + ' — 카페24 · 심폴 ' + (품절 ? '품절했습니다' : '다시 팝니다')); return; }
    u.확인({
      제목: 이름 + ' — 일부만 됐습니다',
      본문: u.안전(줄('카페24', 카)) + '<br>' + u.안전(줄('심폴', 심)) +
            '<br><br>v3 에는 ' + (품절 ? '품절' : '판매중') + ' 로 적혀 있습니다.',
      확인글: '알겠습니다', 취소글: '닫기'
    }, function () {});
  }

  /* 물어보고 → 예면 그때(true) 로 v3 에 먼저 적게 하고 → 마켓에 민다.
     🔴 취소하시면 그때(false) — **v3 상태도 안 바꾼다.** 마켓과 v3 가 어긋나는 게 제일 나쁘다. */
  function 물어보고밀기(품목, 품절, 그때) {
    var 이름 = 이름표(품목);
    var 클 = 클라이언트();

    if (!클) {
      u.확인({
        제목: 이름 + ' — 서버가 꺼져 있습니다',
        본문: '마켓에는 못 보냅니다. <b>v3 에만</b> ' + (품절 ? '품절' : '판매중') + ' 로 적을까요?',
        확인글: 'v3 에만 적는다'
      }, 그때);
      return;
    }

    u.확인({
      제목: 이름 + (품절 ? ' — 모든 마켓에서 품절할까요?' : ' — 다시 팔까요?'),
      본문: '자사몰 · 심폴을 <b>' + (품절 ? '품절</b>로' : '판매중</b>으로') + ' 바꿉니다.<br>' +
            '쿠팡 등 오픈마켓은 <b>마켓플러스에서 손으로</b> 하셔야 합니다.',
      확인글: 품절 ? '품절한다' : '다시 판다',
      위험: 품절
    }, function (예) {
      if (!예) { 그때(false); return; }
      그때(true);                    // v3 에 먼저 적는다 — 마켓이 느려도 화면은 바로 닫힌다
      밀기(품목, 품절);
    });
  }

  function 밀기(품목, 품절) {
    var 이름 = 이름표(품목), 클 = 클라이언트();
    if (!클) return;
    u.토스트(이름 + ' — 마켓에 보내는 중…');
    Promise.resolve(클.functions.invoke('market-soldout', {
      body: { 품목코드: 품목.품목코드, 품절: !!품절 }
    })).then(function (답) {
      if (답 && 답.error) throw 답.error;
      var d = (답 && 답.data) || {};
      if (!d.ok) throw new Error(d.오류 || '함수가 거절했습니다');
      알리기(이름, 품절, d);
    }).catch(function (e) {
      u.확인({
        제목: 이름 + ' — 마켓에 못 보냈습니다',
        본문: u.안전(String((e && e.message) || e)) +
              '<br><br>v3 에는 ' + (품절 ? '품절' : '판매중') + ' 로 적혀 있습니다. 마켓은 손으로 봐 주세요.',
        확인글: '알겠습니다', 취소글: '닫기'
      }, function () {});
    });
  }

  ZG.마켓품절 = { 물어보고밀기: 물어보고밀기, 밀기: 밀기 };
})(window.ZG);
