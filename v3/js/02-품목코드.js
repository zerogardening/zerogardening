/* 02-품목코드 — 학명 정규화 · 앞3자 · 일련번호 · 중복판정 · 규격 (설계 §6) */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  // 실데이터에 따옴표가 세 종류 섞여 있다. 정규화 없이는 같은 식물을 다른 식물로 본다
  function 학명정규화(원문) {
    var s = String(원문 == null ? '' : 원문);
    s = s.replace(/[‘’´`]/g, "'");
    // × 는 앞뒤 공백째로, ASCII x 는 홀로 선 것만 — "Salix alba" 가 망가지면 안 된다
    s = s.replace(/\s*×\s*/g, ' x ');
    s = s.replace(/\s+x\s+/g, ' x ');
    s = s.normalize('NFD').replace(/[̀-ͯ]/g, '');
    s = s.replace(/\s+/g, ' ').trim();
    return s;
  }

  function 학명키(원문) { return 학명정규화(원문).toLowerCase(); }

  function 학명3자(학명) {
    var s = 학명정규화(학명);
    var 품종맞음 = s.match(/'([^']+)'/);
    var 품종 = 품종맞음 ? 품종맞음[1].trim() : '';
    var 속명 = (s.split(' ')[0] || '').replace(/[^A-Za-z]/g, '');

    var 코드;
    if (품종 && /^[A-Za-z]/.test(품종)) 코드 = 속명.slice(0, 2) + 품종.charAt(0);
    else 코드 = 속명.slice(0, 3);

    코드 = 코드.toUpperCase();
    while (코드.length < 3) 코드 += 'X';   // 속명이 2자 미만인 이상값 방어
    return 코드;
  }

  var 치환표 = { 4: 10, 5: 15, 6: 18, 7: 21, 9: 27 };

  // 0 = 규격 외(구근·뿌리묘 등 화분묘가 아닌 것). 구근 크기·뿌리묘 구분은 상품명으로 한다 (우람님 9/14)
  var 규격외cm = 0, 규격외 = '규격 외';
  function 규격이름(cm) { return Number(cm) === 규격외cm ? 규격외 : cm + 'cm 포트'; }

  function 규격정규화(입력) {
    var 원문 = String(입력 == null ? '' : 입력).trim();

    // 「규격 외」를 다시 넣어도 통과해야 한다 (재고수정 칸이 되먹인다)
    if (원문 === 규격외) return { 규격cm: 규격외cm, 규격: 규격외 };

    // 부분 추출은 「1년생」·「15.5」·「abc12」를 통과시킨다. 전체일치만 받는다 (설계 §6-4)
    var 치맞음 = 원문.match(/^(\d{1,3})\s*치$/);
    if (치맞음) {
      var 치수 = parseInt(치맞음[1], 10);
      var 치cm = 치환표[치수];
      if (!치cm) return { 오류: 치수 + '치는 알 수 없는 규격입니다 — cm 로 넣어주세요' };
      return { 규격cm: 치cm, 규격: 규격이름(치cm) };
    }

    // 이 함수가 내놓은 「10cm 포트」를 다시 넣어도 그대로 통과해야 한다 (재고수정 칸이 되먹인다)
    var 숫자맞음 = 원문.match(/^(\d{1,3})(?:\s*cm(?:\s*포트)?)?$/);
    if (!숫자맞음) return { 오류: '규격은 숫자만 넣어주세요 — 10 · 15 처럼 cm 숫자로, 규격 외는 0 으로 넣어주세요' };

    var cm = parseInt(숫자맞음[1], 10);
    if (!(cm >= 0 && cm <= 999)) return { 오류: '규격은 0~999 사이여야 합니다 — 규격 외는 0' };
    return { 규격cm: cm, 규격: 규격이름(cm) };
  }

  function 다음번호(같은3자) {
    var 최대 = 0;
    같은3자.forEach(function (p) {
      var n = parseInt(p.일련번호, 10);
      if (!isNaN(n) && n > 최대) 최대 = n;
    });
    if (최대 >= 99) return null;              // 꽉 찼다
    return String(최대 + 1).padStart(2, '0');
  }

  /* 코드계산 — 이 화면의 핵심 로직 (설계 §6-5)
     반환 상태: "새것" | "이미있음" | "확인필요" | "오류" */
  function 코드계산(학명, 규격cm, 품목목록) {
    var 세자 = 학명3자(학명);
    var 키 = 학명키(학명);
    var 같은3자 = 품목목록.filter(function (p) { return p.학명3 === 세자; });
    var 같은식물 = 같은3자.filter(function (p) { return p.학명키 === 키; });

    // 갈래 A — 같은 식물이 이미 있다
    if (같은식물.length) {
      var 번호 = 같은식물[0].일련번호;
      var 코드 = 세자 + 번호 + '-' + 규격cm;
      var 기존 = 같은식물.find(function (p) { return p.규격cm === 규격cm; });
      if (기존) return { 상태: '이미있음', 코드: 코드, 기존품목: 기존 };

      var 다음 = 다음번호(같은3자);
      if (!다음) return { 상태: '오류', 메시지: 세자 + ' 의 일련번호가 꽉 찼습니다' };
      return {
        상태: '확인필요', 확정코드: 코드, 대안코드: 세자 + 다음 + '-' + 규격cm,
        충돌: 같은식물, 접두: 세자 + 번호, 기본선택: '같은식물',
        번호같음: 번호, 번호다름: 다음
      };
    }

    // 갈래 B — 앞 3자만 같고 학명이 다르다. 반드시 물어본다
    if (같은3자.length) {
      var 번호목록 = 같은3자.map(function (p) { return p.일련번호; })
        .sort().filter(function (v, i, a) { return a.indexOf(v) === i; });
      var 마지막 = 번호목록[번호목록.length - 1];
      var 다음B = 다음번호(같은3자);
      if (!다음B) return { 상태: '오류', 메시지: 세자 + ' 의 일련번호가 꽉 찼습니다' };
      return {
        상태: '확인필요', 확정코드: 세자 + 마지막 + '-' + 규격cm, 대안코드: 세자 + 다음B + '-' + 규격cm,
        충돌: 같은3자, 접두: 세자 + 마지막, 기본선택: null,
        번호같음: 마지막, 번호다름: 다음B
      };
    }

    // 갈래 C — 완전히 새 식물
    return { 상태: '새것', 코드: 세자 + '01-' + 규격cm };
  }

  /* ══════════ 상세페이지 폼 갈래 — 구근이냐 화분묘냐 (2026-09-14 우람님) ══════════
     🔴 한 곳에서만 가른다. 06g(사진 칸) · 06h·06j(구역 이름) · 지시함.py 가 이걸 본다.
        py 쪽 짝은 도구/제작요청.py 의 `구근인가()` 다 — **둘의 낱말 목록이 같아야 한다.**
     🔴 규격 0(규격 외)에는 구근과 뿌리묘가 섞인다(우람님 9/14 「구분은 상품명으로」).
        그래서 규격만으로는 못 가른다 — 이름을 같이 본다. */
  var 구근낱말 = ['튤립', '수선화', '무스카리', '크로커스', '히아신스', '알리움', '상사화',
                '아네모네', '라넌큘러스', '프리지아', '아마릴리스', '글라디올러스', '설강화',
                '시클라멘', '백합', '나리', '달리아', '아이리스', '칼라'];

  function 구근인가(품목) {
    if (!품목) return false;
    var 이름 = String(품목.유통명 || '');
    if (이름.indexOf('구근') >= 0) return true;          // 상품명에 박아 넣으신 경우
    /* 🔴 빈 규격을 0 으로 보면 안 된다 — Number(null) 도 Number('') 도 0 이다.
       py 짝(제작요청.py)은 빈 값을 화분묘로 보므로 여기서도 같이 본다.
       한쪽만 구근으로 보면 화면의 칸 수와 자동 착수 조건이 갈린다. */
    var 규격 = 품목.규격cm;
    if (규격 === null || 규격 === undefined || String(규격).trim() === '') return false;
    if (Number(규격) !== 규격외cm) return false;          // 규격 외가 아니면 화분묘다
    for (var i = 0; i < 구근낱말.length; i++) {
      if (이름.indexOf(구근낱말[i]) === 0) return true;
    }
    return false;
  }

  /* [번호, 이름, 찍는자리, 안 채워도 되는 칸] — 06g 가 그대로 그린다.
     🔴 구근은 일곱 칸을 다 안 채운다 (우람님 9/14 「규격외는 다 안 채워도 된다」) —
        2·3·5 구역이 도해라 사진이 아예 필요 없다. 필수는 넷뿐이다. */
  var 사진자리 = {
    화분묘: [[1, '대표이미지 배경'], [2, '구역1 메인'], [3, '구역2 꽃'], [4, '구역3 잎'], [5, '구역4 재배'],
           [6, '추가', false, true], [7, '추가', false, true], [8, '추가', false, true], [9, '추가', false, true],
           [10, '구역6 실촬영 · 화분 하나', true], [11, '구역6 실촬영 · 여러 포기', true]],
    구근:  [[1, '대표이미지 배경'], [2, '구역1 표지 꽃'],
           [3, '구역2 꽃', false, true], [4, '구역4 꽃', false, true],
           [10, '구역6 구근 · 한 알', true], [11, '구역6 구근 · 여러 알', true]]
  };

  var 구역이름들 = {
    화분묘: { '1': '소개', '2': '꽃', '3': '잎', '4': 'How to grow', '5': '식재 간격', '6': '실촬영' },
    구근:  { '1': '표지', '2': '심기', '3': '심는 법', '4': 'How to grow', '5': '구근 크기', '6': '보내드리는 상품' }
  };

  function 폼(품목) { return 구근인가(품목) ? '구근' : '화분묘'; }

  ZG.상세폼 = {
    구근인가: 구근인가,
    폼: 폼,
    사진자리: function (품목) { return 사진자리[폼(품목)]; },
    구역이름: function (품목) { return 구역이름들[폼(품목)]; }
  };

  ZG.품목코드 = {
    학명정규화: 학명정규화,
    학명키: 학명키,
    학명3자: 학명3자,
    규격정규화: 규격정규화,
    규격이름: 규격이름,
    다음번호: 다음번호,
    코드계산: 코드계산
  };
})(window.ZG);
