      /* 넘길 0(품목코드 없음)이어도 보류는 푼다 — 08g 「미차감」처럼 송장은 보낸다 */
      if (!갈래.넘길.length) return;
      결.출고 += B.출고넣기(갈래.넘길, 오늘, 색인, { 배치: 배치, 운송장번호: 건.송장 }).length;
