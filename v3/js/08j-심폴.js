/* 08j-심폴 — 심폴(simpol.co.kr) 주문 파일 자료층 (8단계 설계 §2~§6). 화면 없음.
   심폴 31칸을 카페24 27칸으로 세워 주면 08h·08i 가 지금 길 그대로 돈다.

   🔴 아래 「짝표」는 심폴 전용이 아니다 (2026-08-10 우람님 지시로 넓혔다).
      판매처를 가리지 않고 `원본코드 → v3 품목코드` 를 기억한다 — 카페24·자동수집도 같이 탄다.
      바깥에서는 `ZG.짝` 이라는 이름으로 부른다. 저장키·Supabase 표 이름(`v3_심폴짝`)은
      이사가 번거로워 그대로 뒀다. 파일명·표이름만 옛 이름이고 기능은 전 판매처 공용이다.

   🔴 핵심 한 수 — 심폴 상품코드를 27칸의 7번(자체품목코드) 자리에 넣는다.
      그래서 줄.원본코드가 언제나 심폴 상품코드가 되고, 08h.중복키·08i 를 한 줄도 안 고친다.
   🔴 이름으로 자동 매칭하지 않는다. 유통명이 같은 품목이 여럿이라 엉뚱한 상품이 나간다.
      자동은 상품코드 열쇠 하나로만 한다. */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  function 글(v) { return String(v == null ? '' : v); }
  function 다듬기(v) { return 글(v).trim(); }
  function 두자(v) { return String(v).padStart(2, '0'); }

  /* 심폴 머리글은 「전화번호(XX-XXXX-XXXX)」처럼 괄호 설명이 붙는다 — 공백과 괄호 이하를 떼고 본다 */
  function 심폴키(v) { return 글(v).replace(/\s/g, '').replace(/\(.*$/, ''); }

  var 심폴필수 = ['일자', '받는사람', '거래번호', '상품코드', '갯수', '상품가격'];

  /* 카페24 27칸 ← 심폴 칸 (설계 §2). null 은 빈 칸으로 둔다 */
  var 지도 = [
    '@심폴', null, '거래번호', '@일자', '상품명', '@상품코드', '@빈', '@상품코드',
    null, null, '결제상태', '상품가격', '갯수', '받는사람', '우편번호', '주소',
    null, '비상전화', '전화번호', '전달사항', '주문자', null, null,
    null, '주문자전화', null, null
  ];

  function 감지(머리행) {
    var 자리 = {};
    (머리행 || []).forEach(function (v, i) {
      var 이름 = 심폴키(v);
      if (이름 && 자리[이름] == null) 자리[이름] = i;
    });
    var 없는 = 심폴필수.filter(function (k) { return 자리[k] == null; });
    return 없는.length ? null : { 자리: 자리 };
  }

  /* 20260808 · 2026-8-8 · Date 를 08h.날짜만들기가 그대로 받는 모양까지만 편다.
     🔴 숫자 20260808 을 그대로 넘기면 08a 가 ms 로 읽어 1970-08-23 이 된다 */
  function 날짜글(v) {
    if (v instanceof Date) return v;
    var s = 다듬기(v);
    var m = s.match(/^(\d{4})(\d{2})(\d{2})$/);
    if (m) return m[1] + '-' + m[2] + '-' + m[3];
    m = s.match(/^(\d{4})[-.\/](\d{1,2})[-.\/](\d{1,2})/);
    if (m) return m[1] + '-' + 두자(m[2]) + '-' + 두자(m[3]);
    return s;   // 못 알아보면 그대로 — 08h 가 「날짜오류」 갈래로 걸러 화면에 보여준다
  }

  /* 심폴 상품코드는 앞 0 이 있는 18자리다. 숫자로 읽히면 앞 0 이 날아가므로 되살린다 */
  function 상품코드글(v) {
    if (typeof v === 'number') return String(v).padStart(18, '0');
    return 다듬기(v);
  }

  function 바꾸기(행들, 심) {
    var 자리 = 심.자리;
    /* 심폴은 「28181 」처럼 꼬리 공백을 실어 보낸다 — 여기서 떼어야 로젠 파일에 그대로 안 실린다 */
    function 값(행, 이름) {
      var i = 자리[이름];
      var v = i == null ? '' : ((행 || [])[i] == null ? '' : 행[i]);
      return typeof v === 'string' ? v.trim() : v;
    }
    var 새행들 = [[]];   // 0번은 빈 머리행 — 08h 의 `for (i = 1; …)` 를 안 고치려고 자리를 맞춘다
    for (var i = 1; i < 행들.length; i++) {
      var 행 = 행들[i] || [];
      /* 🔴 빈 줄은 빈 줄로 넘긴다 — 0번 칸에 '심폴'을 박아 버리면 08h.빈행인가 를 못 지나간다 */
      if (행.every(function (c) { return 다듬기(c) === ''; })) { 새행들.push([]); continue; }
      var 코드 = 상품코드글(값(행, '상품코드'));
      새행들.push(지도.map(function (열) {
        if (열 == null || 열 === '@빈') return '';
        if (열 === '@심폴') return '심폴';
        if (열 === '@일자') return 날짜글(값(행, '일자'));
        if (열 === '@상품코드') return 코드;
        return 값(행, 열);
      }));
    }
    /* 27칸을 표준 순서로 세웠으므로 자리표는 항등표다 — 08h 의 원본27()·칸글() 이 그대로 돈다 */
    var 항등 = {};
    ZG.주문올리기.칸이름들().forEach(function (이름, n) { if (항등[이름] == null) 항등[이름] = n; });
    return { 행들: 새행들, 자리: 항등 };
  }

  /* ══ 짝표 — 심폴 상품코드 ↔ v3 품목코드 (설계 §5) ══ */

  function 키() { return ZG.저장소.키.심폴짝; }
  function 짝목록() { return ZG.저장소.읽기(키()); }

  function 짝표() {
    var 표 = {};
    짝목록().forEach(function (r) { if (r && r.id) 표[r.id] = r.붙인품목코드 || ''; });
    return 표;
  }

  /* 🔴 v3 품목코드 칸 이름은 `붙인품목코드` 다. `품목코드` 로 지으면
     01-저장소의 아이디(r) = r.id || r.품목코드 가 엉뚱한 줄을 잡는다 */
  function 짝쓰기(상품코드, 품목코드, 상품명) {
    var 저 = ZG.저장소, 때 = Date.now();
    var 있나 = 짝목록().some(function (r) { return r.id === 상품코드; });
    if (있나) return 저.바꾸기(키(), 상품코드, { 붙인품목코드: 품목코드, 심폴상품명: 상품명 || '', 고친때: 때 });
    return 저.덧붙이기(키(), {
      id: 상품코드, 붙인품목코드: 품목코드, 심폴상품명: 상품명 || '', 만든때: 때, 고친때: 때
    });
  }

  function 짝풀기(상품코드) { return ZG.저장소.지우기(키(), 상품코드); }

  /* ══ 되붙이기 — 붙이기·떼기를 한 함수로 (설계 §6) ══ */

  /* 🔴 묶음키·중복키는 다시 계산하지 않는다. 원본코드가 짝을 짓든 말든 늘 심폴 상품코드라
     같은 파일을 짝짓기 전후로 올려도 똑같이 「이미 있는 줄」로 걸린다.

     🔴 심폴과 그 밖의 판매처는 규칙이 다르다 (2026-08-10) —
        · 심폴  : 원본코드가 언제나 심폴 상품코드라 자동 매칭이 애초에 불가능하다.
                  짝이 곧 전부라 짝을 풀면 품목도 같이 비운다(여태 동작 그대로).
        · 그 밖 : 원본코드가 v3 품목코드일 수 있어 이미 저절로 붙은 줄이 있다.
                  **붙어 있는 줄은 절대 덮지 않는다** — 짝이 자동 매칭을 이기면 안 된다.
                  짝도 없으면 그냥 둔다(빈칸을 다시 비우느라 유통명을 날리지 않는다). */
  function 되붙이기(항목들) {
    var 표 = 짝표(), 마스터 = {};
    ZG.저장소.품목들().forEach(function (p) { 마스터[p.품목코드] = p; });
    (항목들 || []).forEach(function (것) {
      var r = 것 && 것.줄;
      if (!r) return;
      var 심 = r.판매처 === '심폴';
      var p = 마스터[표[r.원본코드]] || null;
      if (!심 && (r.품목코드 || !p)) return;
      r.품목코드 = p ? p.품목코드 : '';
      r.유통명 = p ? p.유통명 : (것.상품명 || '');   // 못 찾으면 원본 상품명 (로젠 E열이 이걸 쓴다)
      r.학명 = p ? p.학명 : '';
      r.규격 = p ? p.규격 : '';
    });
  }

  /* 이미 저장된 주문 줄에 짝을 뒤늦게 붙인다 — 자동수집(Edge Function)은 서버에서 매칭하므로
     짝표를 모른다. 수집 뒤 여기서 한 번 훑어 못 붙은 줄만 메운다.
     🔴 붙어 있는 줄·원본코드 없는 줄은 건드리지 않는다. 묶음키는 사람 정보로만 만들어져(08a)
        품목이 바뀌어도 안 흔들리므로 다시 계산하지 않는다 */
  function 저장된줄되붙이기() {
    var 저 = ZG.저장소, 표 = 짝표(), 마스터 = {}, 센 = 0;
    저.품목들().forEach(function (p) { 마스터[p.품목코드] = p; });
    저.읽기(저.키.주문).forEach(function (r) {
      if (!r || r.품목코드 || !r.원본코드) return;
      var p = 마스터[표[r.원본코드]];
      if (!p) return;
      저.바꾸기(저.키.주문, r.id, {
        품목코드: p.품목코드, 유통명: p.유통명, 학명: p.학명, 규격: p.규격
      });
      센++;
    });
    return 센;
  }

  ZG.심폴 = {
    감지: 감지, 바꾸기: 바꾸기, 날짜글: 날짜글,
    짝표: 짝표, 짝목록: 짝목록, 짝쓰기: 짝쓰기, 짝풀기: 짝풀기,
    되붙이기: 되붙이기, 저장된줄되붙이기: 저장된줄되붙이기
  };

  /* 판매처를 안 가리는 이름 — 새로 쓰는 자리는 전부 이걸 부른다 (같은 함수다) */
  ZG.짝 = {
    짝표: 짝표, 짝목록: 짝목록, 짝쓰기: 짝쓰기, 짝풀기: 짝풀기,
    되붙이기: 되붙이기, 저장된줄되붙이기: 저장된줄되붙이기
  };
})(window.ZG);
