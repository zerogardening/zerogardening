  /* ── 옵션 풀이 — 짝 열쇠는 여기서만 만든다 (21단계 설계 §1) ──
     🔴 도구/edge-주문수집/index.ts 도 같은 규칙을 따라야 한다. 한쪽만 고치면 열쇠가 어긋나
        손으로 지은 짝을 자동수집이 못 알아본다.
     「수량=3개」처럼 개수만 다른 옵션은 한 품목이라 원본코드가 그대로 열쇠다. 「색상=3.휴케라 라임리키」처럼
     옵션이 곧 다른 식물이면 옵션마다 열쇠가 따로다 — 옛날엔 원본코드 하나에 묶여 휴케라 6종이 전부 한 품목으로 붙었다 */
  var 개수꼴 = [
    /^\d+\s*(개|주|구|포기|묶음|세트|팩)?$/,
    /^(단일상품|단품|기본)$/,
    /^\d+(\.\d+)?\s*(cm|mm|센치)?\s*(화분|포트)?$/i
  ];

  function 옵션풀이(원본코드, 옵션원문) {
    var 원 = 다듬기(옵션원문);
    var 축들 = 원 ? 원.split(/\s*,\s*(?=[^,=]+=)/) : [];
    var 품목축 = [], 수량입수 = 0, 꼬리입수 = 0, 개수입수 = 0;
    축들.forEach(function (축) {
      var m = 축.match(/^\s*([^=]*?)\s*=\s*(.*)$/);
      var 이름 = m ? m[1] : '', 값 = 다듬기(m ? m[2] : 축);
      var t = 값.match(/\s*[(（]\s*(\d+)\s*개\s*[)）]\s*$/);
      var 알 = (t ? 값.slice(0, t.index) : 값).replace(/\s+/g, ' ').trim();
      var 수량축 = 이름.replace(/\s/g, '') === '수량';
      if (t && !꼬리입수) 꼬리입수 = Number(t[1]) || 0;
      var n = 값.match(/^(\d+)\s*개/);   // 옛 08h 처럼 `수량=3개입` 도 3
      if (수량축 && n && !수량입수) 수량입수 = Number(n[1]) || 0;
      var 개수 = 수량축 || !알 || 개수꼴.some(function (re) { return re.test(알); });
      if (개수) {
        var k = 알.match(/^(\d+)\s*개$/);
        if (k && !개수입수) 개수입수 = Number(k[1]) || 0;
        return;
      }
      품목축.push({ 이름: 이름, 값: 값, 알: 알 });
    });
    var 코드 = 다듬기(원본코드) ? 글(원본코드) : '';
    var 품목옵션 = 품목축.length > 0;
    var 옵션값 = 품목축.map(function (x) { return x.알; }).join(' / ');
    return {
      열쇠: !코드 ? '' : (품목옵션 ? 코드 + '§' + 옵션값 : 코드),
      품목옵션: 품목옵션,
      옵션이름: 품목축.map(function (x) { return x.이름; }).filter(Boolean).join(', '),
      옵션값: 옵션값,
      표시값: 품목축.map(function (x) { return x.값; }).join(', '),
      입수: 수량입수 || 꼬리입수 || 개수입수 || 0
    };
  }

  /* 🔴 옵션이 품목인 줄은 옛 짝(id=원본코드)을 쓰지 않는다 — 그게 라임리키가 골든제브라로 붙은 길이다.
     「옵션 구분 없이 하나로」(옵션무시) 로 지은 짝만 상품 전체를 덮는다 */
  function 짝찾기(줄, 색인) {
    색인 = 색인 || 짝색인();
    var 풀 = 옵션풀이(줄 && 줄.원본코드, 줄 && 줄.옵션원문);
    if (!풀.열쇠) return null;
    if (!풀.품목옵션) return 색인[풀.열쇠] || null;
    var 옛 = 색인[줄.원본코드];
    if (옛 && 옛.옵션무시) return 옛;
    return 색인[풀.열쇠] || null;
  }

  /* 짝이 붙은 뒤의 옵션입수 (설계 §4). 🔴 곱하지 않는다 — 판매단위 5 · 「(5개)」 가 25가 되면
     08f 재고 차감까지 다섯 배로 간다. 쿠팡은 쿠팡단위 방식이라 옵션 쪽을 그대로 둔다 */
  function 입수정하기(줄, 품목, 풀이) {
    if (!품목 || 줄.판매처 === '쿠팡') return 줄.옵션입수;
    var 단위 = Number(품목.판매단위) || 1;
    if (!풀이 || !풀이.품목옵션) return 단위;
    return Math.max(단위, 풀이.입수 || 1);
  }

  /* 🔴 v3 품목코드 칸 이름은 `붙인품목코드` 다. `품목코드` 로 지으면
     01-저장소의 아이디(r) = r.id || r.품목코드 가 엉뚱한 줄을 잡는다.
     덧 — { 옵션값, 옵션무시 } (jsonb 안이라 표를 안 고친다) */
  function 짝쓰기(열쇠, 품목코드, 상품명, 덧) {
    var 저 = ZG.저장소, 때 = Date.now();
    var 바뀜 = { 붙인품목코드: 품목코드, 심폴상품명: 상품명 || '', 고친때: 때 };
    Object.keys(덧 || {}).forEach(function (k) { 바뀜[k] = 덧[k]; });
    var 있나 = 짝목록().some(function (r) { return r.id === 열쇠; });
    if (있나) return 저.바꾸기(키(), 열쇠, 바뀜);
    바뀜.id = 열쇠; 바뀜.만든때 = 때;
    return 저.덧붙이기(키(), 바뀜);
  }

  function 짝풀기(열쇠) { return ZG.저장소.지우기(키(), 열쇠); }

  function 마스터표() {
    var 표 = {};
    ZG.저장소.품목들().forEach(function (p) { 표[p.품목코드] = p; });
    return 표;
  }

  /* ══ 되붙이기 — 붙이기·떼기를 한 함수로 (설계 §6) ══ */

  /* 🔴 묶음키·중복키는 다시 계산하지 않는다. 원본코드가 짝을 짓든 말든 늘 심폴 상품코드라
     같은 파일을 짝짓기 전후로 올려도 똑같이 「이미 있는 줄」로 걸린다.

     🔴 심폴과 그 밖의 판매처는 규칙이 다르다 (2026-08-10) —
        · 심폴  : 원본코드가 언제나 심폴 상품코드라 자동 매칭이 애초에 불가능하다.
                  짝이 곧 전부라 짝을 풀면 품목도 같이 비운다(여태 동작 그대로).
        · 그 밖 : 원본코드가 v3 품목코드일 수 있어 이미 저절로 붙은 줄이 있다.
                  **붙어 있는 줄은 절대 덮지 않는다** — 짝이 자동 매칭을 이기면 안 된다.
                  짝도 없으면 그냥 둔다(빈칸을 다시 비우느라 유통명을 날리지 않는다). */
  function 되붙이기(항목들) {
    var 색인 = 짝색인(), 마스터 = 마스터표();
    (항목들 || []).forEach(function (것) {
      var r = 것 && 것.줄;
      if (!r) return;
      var 심 = r.판매처 === '심폴' || r.판매처 === '당근';
      var 짝 = 짝찾기(r, 색인);
      var p = (짝 && 마스터[짝.붙인품목코드]) || null;
      if (!심 && (r.품목코드 || !p)) return;
      r.품목코드 = p ? p.품목코드 : '';
      r.유통명 = p ? p.유통명 : (것.상품명 || '');   // 못 찾으면 원본 상품명 (로젠 E열이 이걸 쓴다)
      r.학명 = p ? p.학명 : '';
      r.규격 = p ? p.규격 : '';
      /* 🔴 짝이 뒤늦게 붙을 때도 입수를 다시 정한다 — 안 하면 짝짓기 전에 저장된
         옵션입수(1)가 그대로 남아 여기서 고쳐도 소용없다(2026-09-28) */
      if (p) r.옵션입수 = 입수정하기(r, p, 옵션풀이(r.원본코드, r.옵션원문));
    });
  }

  /* 이미 저장된 주문 줄에 짝을 뒤늦게 붙인다 — 자동수집(Edge Function)은 서버에서 매칭하므로
     짝표를 모른다. 수집 뒤 여기서 한 번 훑어 못 붙은 줄만 메운다.
     🔴 붙어 있는 줄·원본코드 없는 줄은 건드리지 않는다. 묶음키는 사람 정보로만 만들어져(08a)
        품목이 바뀌어도 안 흔들리므로 다시 계산하지 않는다 */
  function 저장된줄되붙이기() {
    var 저 = ZG.저장소, 색인 = 짝색인(), 마스터 = 마스터표(), 센 = 0;
    저.읽기(저.키.주문).forEach(function (r) {
      if (!r || r.품목코드 || !r.원본코드) return;
      var 짝 = 짝찾기(r, 색인);
      var p = 짝 && 마스터[짝.붙인품목코드];
      if (!p) return;
      저.바꾸기(저.키.주문, r.id, {
        품목코드: p.품목코드, 유통명: p.유통명, 학명: p.학명, 규격: p.규격,
        옵션입수: 입수정하기(r, p, 옵션풀이(r.원본코드, r.옵션원문))
      });
      센++;
    });
    return 센;
  }

