/* 08f-배송완료 — 로젠 「출력완료」 파일을 읽어 출고를 만든다 (6단계-4 설계 §2·§3·§5·§6)
   🔴 화면이 없다. 여기는 자료만 만진다 — 창은 08g.
   🔴 재고 차감의 근거는 로젠 파일이 아니라 v3 주문줄(`zg.v3.주문`)이다.
      로젠 파일은 「어느 주문번호가 실제로 나갔나」를 알려주는 신호로만 쓴다.
      로젠 AI열에 물품코드가 실려 오지만 쓰지 않는다 — 합포장이면 슬래시로 붙어 오고 빈 줄도 있다. */
window.ZG = window.ZG || {};
(function (ZG) {
  'use strict';

  function 값(v) { return String(v == null ? '' : v).trim(); }
  function 글(v) { return String(v == null ? '' : v).replace(/[\s ]/g, ''); }
  function 이름키(v) { return String(v == null ? '' : v).normalize('NFC').replace(/\s/g, ''); }

  /* ══ §2 파일 읽기 ══ */

  /* 🔴 「4행부터」를 index 로 박지 않는다. 0~5행 안에서 자리가 맞는 마지막 줄이 머리글이다
     (실물은 2·3행 두 줄 머리글이라 3행이 잡힌다). 로젠이 제목 줄을 하나 늘려도 안 깨진다 */
  function 머리찾기(행들) {
    var 찾음 = -1;
    for (var i = 0; i < 6 && i < (행들 || []).length; i++) {
      var r = 행들[i] || [];
      if (글(r[3]) === '운송장번호' && 글(r[18]) === '주문번호') 찾음 = i;
    }
    return 찾음;
  }

  function 읽기시트(행들) {
    행들 = 행들 || [];
    var 머리 = 머리찾기(행들);
    /* 🔴 못 찾으면 아무것도 하지 않고 멈춘다. 이 검사가 없으면 엉뚱한 엑셀을 골랐을 때
       전 줄이 「확인 필요」로 떨어지고 「전부 이름으로 찾기」 한 번에 남의 재고가 깎인다 */
    if (머리 < 0) {
      return { ok: false, 오류: '로젠 「출력완료」 파일이 아닌 것 같습니다 — S열이 주문번호가 아닙니다.', 총: 0, 무시: 0, 줄들: [] };
    }

    var 줄들 = [], 무시 = 0;
    for (var i = 머리 + 1; i < 행들.length; i++) {
      var r = 행들[i] || [];
      var 빔 = r.every(function (c) { return 값(c) === ''; });
      if (빔) continue;                                   // 아예 빈 줄은 세지도 않는다
      var 운송장번호 = 값(r[3]), 주문번호 = 값(r[18]);
      /* 둘 다 비면 그 줄 자체를 무시 — 실물 마지막 「합계」 줄이 여기서 걸러진다.
         운송장번호만 있고 주문번호가 빈 줄은 무시가 아니다(전화주문 → 「확인 필요」) */
      if (!운송장번호 && !주문번호) { 무시++; continue; }
      줄들.push({
        순번: 줄들.length + 1,
        운송장번호: 운송장번호,
        수하인: 값(r[6]),
        박스: Number(값(r[11]).replace(/,/g, '')) || 1,
        주문번호: 주문번호
      });
    }
    return { ok: true, 오류: '', 총: 줄들.length, 무시: 무시, 줄들: 줄들 };
  }

  /* ══ §3 매칭 · 방패 ══ */

  /* 🔴 실행마다 한 번만 만든다. 줄마다 저장소를 읽으면 이사 데이터에서 O(n²)가 된다 */
  function 색인만들기() {
    var 저 = ZG.저장소;
    var 주문들 = 저.읽기(저.키.주문);
    var 주문번호별 = {}, 이미나감 = {};
    주문들.forEach(function (r) {
      var n = 값(r.주문번호);
      if (!n) return;                       // 🔴 빈 주문번호끼리는 절대 맞다고 하지 않는다
      (주문번호별[n] = 주문번호별[n] || []).push(r);
    });
    저.읽기(저.키.출고).forEach(function (r) { if (r.주문id) 이미나감[r.주문id] = 1; });
    return { 주문번호별: 주문번호별, 이미나감: 이미나감, 주문들: 주문들 };
  }

  function 주문찾기(주문번호, 색인) {
    var n = 값(주문번호);
    if (!n) return [];
    return (색인.주문번호별[n] || []).slice();
  }

  /* 🔴 유일한 관문이다. 출고를 만드는 코드는 여기를 통과한 줄만 받는다 (6단계-3 설계 §4) */
  function 넘길줄만(주문줄들, 색인) {
    var 넘길 = [], 걸린 = [];
    (주문줄들 || []).forEach(function (줄) {
      var 사유 = '';
      if (줄.서비스 === true) 사유 = '서비스';                 // 넣던 그 순간 이미 출고가 만들어졌다
      else if (색인.이미나감[줄.id]) 사유 = '이미';            // 변환을 두 번 돌린 사고까지 이 줄이 막는다
      else if (!줄.품목코드) 사유 = '품목미확인';
      else if (ZG.주문자료.수량(줄) <= 0) 사유 = '수량0';
      if (사유) 걸린.push({ 줄: 줄, 사유: 사유 });
      else 넘길.push(줄);
    });
    return { 넘길: 넘길, 걸린: 걸린 };
  }

  /* 출고일 = 처리하는 날. 로젠 출력완료 파일은 그날 송장을 뽑은 결과라 실제 나간 날이다.
     🔴 새 출고줄에는 반드시 `주문id`를 넣는다 — 안 넣으면 다음 사람이 중복을 못 막는다 */
  function 출고넣기(주문줄들, 출고일, 색인) {
    var 저 = ZG.저장소, 만든 = [];
    (주문줄들 || []).forEach(function (줄) {
      var 것 = 저.덧붙이기(저.키.출고, {
        id: 'sh_' + Date.now().toString(36) + '_' + Math.random().toString(36).slice(2, 7),
        출고일: 출고일, 품목코드: 줄.품목코드, 수량: ZG.주문자료.수량(줄),
        출처: '주문', 주문id: 줄.id, 등록일시: Date.now()
      });
      if (색인) 색인.이미나감[줄.id] = 1;   // 같은 실행 안에서 두 번 깎이지 않게 색인도 같이 올린다
      만든.push(것.id);
    });
    return 만든;
  }

  function 출고되돌리기(출고id들, 색인) {
    var 저 = ZG.저장소, 센수 = 0;
    var 출고 = 저.읽기(저.키.출고);
    (출고id들 || []).forEach(function (id) {
      var 것 = null;
      출고.forEach(function (r) { if (r.id === id) 것 = r; });
      if (저.지우기(저.키.출고, id)) {
        센수++;
        if (색인 && 것 && 것.주문id) delete 색인.이미나감[것.주문id];
      }
    });
    return 센수;
  }

  /* ══ §5 이름으로 주문 찾기 ══
     🔴 NFC + 공백제거 후 완전일치. 부분일치는 안 쓴다 — 「김미정」이 「김미정외1」을 물면 남의 재고가 깎인다.
     묶음키에 주문일을 더해 묶는다 — 같은 사람이 다른 날 시킨 건은 다른 건이다(지난 ⭐ 주문이 섞이면 안 된다) */
  function 이름후보(수하인, 색인) {
    var 키 = 이름키(수하인);
    if (!키) return [];

    var 순서 = [], 표 = {};
    색인.주문들.forEach(function (줄) {
      if (이름키(줄.수령인) !== 키) return;
      if (!넘길줄만([줄], 색인).넘길.length) return;      // 이미 나간 주문은 후보에 안 뜬다
      var k = (줄.묶음키 || ZG.주문자료.묶음키(줄)) + '|' + (줄.주문일 || '');
      var g = 표[k];
      if (!g) {
        g = 표[k] = {
          묶음키: k, 수령인: 줄.수령인 || '', 주문일: 줄.주문일 || '', 판매처: 줄.판매처 || '',
          줄들: [], 총수량: 0, 글: '', 짧은글: ''
        };
        순서.push(g);
      }
      g.줄들.push(줄);
      g.총수량 += ZG.주문자료.수량(줄);
    });

    순서.sort(function (a, b) { return a.주문일 < b.주문일 ? 1 : a.주문일 > b.주문일 ? -1 : 0; });

    순서.forEach(function (g) {
      g.글 = [g.수령인, g.주문일, g.판매처, 품목글(g.줄들), '총 ' + g.총수량 + '주'].filter(Boolean).join(' · ');
      g.짧은글 = [g.수령인, (g.주문일 || '').slice(5), 차감글(g.줄들)].filter(Boolean).join(' · ');
    });
    return 순서.slice(0, 8);
  }

  function 코드모음(줄들) {
    var 것들 = [];
    (줄들 || []).forEach(function (r) {
      var c = r.품목코드 || '';
      if (c && 것들.indexOf(c) < 0) 것들.push(c);
    });
    return 것들;
  }

  function 품목글(줄들) {
    var 것들 = 코드모음(줄들);
    if (!것들.length) return '';
    return 것들[0] + (것들.length > 1 ? ' 외 ' + (것들.length - 1) + '품목' : '');
  }

  /* 「SAC01-15 6주 차감」 — 그 줄에 무엇을 뺐는지 그대로 적는다 */
  function 차감글(줄들) {
    var 총 = 0;
    (줄들 || []).forEach(function (r) { 총 += ZG.주문자료.수량(r); });
    var 앞 = 품목글(줄들);
    return (앞 ? 앞 + ' ' : '') + 총 + '주 차감';
  }

  /* ══ §6 송장 업로드 파일 ══
     ②로젠 대량등록은 머리글 없음 · ④카페24 송장 업로드는 머리글 있음. 반대로 하면 택배사가 한 줄을 먹는다 */
  function 송장표(줄들) {
    var 표 = [['주문번호', '품목별 주문번호', '운송장번호', '수량']];
    var 센수 = {};
    (줄들 || []).forEach(function (것) {
      /* 넘어간 줄은 안 넣는다. `미차감`은 넣는다 — 재고를 못 깎았을 뿐 실제로 나간 송장이다.
         빼면 그 손님 운송장이 카페24에 안 올라간다 */
      if (['정상', '이미', '처리', '미차감'].indexOf(것.판정) < 0) return;
      var 번호 = 값(것.주문번호) || 값(것.연결주문번호);
      var 품목별 = '';
      if (번호) {
        센수[번호] = (센수[번호] || 0) + 1;
        품목별 = 번호 + '-' + String(센수[번호]).padStart(2, '0');
      }
      표.push([번호, 품목별, 것.운송장번호 || '', Number(것.박스) > 1 ? Number(것.박스) : '']);
    });
    return 표;
  }

  function 내보내기(줄들, 파일명) {
    var 표 = 송장표(줄들);
    var 책 = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(책, XLSX.utils.aoa_to_sheet(표), '송장');
    XLSX.writeFile(책, 파일명);
    return 표.length - 1;
  }

  ZG.배송완료 = {
    머리찾기: 머리찾기, 읽기시트: 읽기시트,
    색인만들기: 색인만들기, 주문찾기: 주문찾기, 넘길줄만: 넘길줄만,
    출고넣기: 출고넣기, 출고되돌리기: 출고되돌리기,
    이름후보: 이름후보, 차감글: 차감글, 품목글: 품목글, 코드모음: 코드모음,
    송장표: 송장표, 내보내기: 내보내기
  };
})(window.ZG);
