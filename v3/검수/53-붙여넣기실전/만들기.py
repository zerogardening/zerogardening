def 상세꼴(상):
    """상세 → (적힌 글, 정답, 꼬리표)"""
    if not 상: return '', '', []
    m = re.search(r'(\d+)\s*동\s*(\d+)\s*호', 상) or re.search(r'(?<![\d-])(\d{2,4})-(\d{2,4})호?$', 상)
    표 = []
    if m and 확(0.6):
        동, 호 = m.group(1), m.group(2)
        k = 고르(('동 호', 3), ('동호붙임', 2), ('하이픈', 3), ('하이픈호', 1), ('호만', 1))
        새 = {'동 호': f'{동}동 {호}호', '동호붙임': f'{동}동{호}호', '하이픈': f'{동}-{호}', '하이픈호': f'{동}-{호}호', '호만': f'{호}호'}[k]
        상 = 상[:m.start()] + 새 + 상[m.end():]; 표.append('동호:' + k)
    건 = re.match(r'^([^\d]+?)\s+(?=\d)', 상)
    if 건 and 확(0.2): 상 = 상[건.end():]; 표.append('건물명뺌')
    return 상.strip(), 상.strip(), 표

