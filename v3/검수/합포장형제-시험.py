# -*- coding: utf-8 -*-
# 합포장 형제 검수 (2026-08-19 우람님 지시)
#   python3 v3/검수/합포장형제-시험.py     ← 그대로 다시 돈다 (playwright 필요)
# 김은정이 2건 시켰는데 로젠이 합포장으로 송장 1장만 준 경우,
#   ① 파일에 안 온 둘째 주문이 같은 운송장번호로 따라붙는가
#   ② 출력번호가 다른 남의 주문 · 이름만 같은 남 · 이미 나간 건은 안 따라붙는가
import pathlib
from playwright.sync_api import sync_playwright

뿌리 = pathlib.Path('/Users/zerogardening/claude-projects/제로가드닝/통합관리/v3')
결과 = []
def 본다(이름, 참, 덧=''):
    결과.append((참, 이름, 덧))

껍데기 = """<!doctype html><meta charset="utf-8"><title>합포장형제 시험</title><body>
<script src="../js/01-저장소.js"></script>
<script src="../js/03-계산.js"></script>
<script src="../js/08a-주문자료.js"></script>
<script src="../js/08f-배송완료.js"></script>
<script>
window.줄 = function (o) {
  return Object.assign({
    id: o.id, 주문번호: o.번호, 주문일: '2026-08-19', 수령인: o.이름, 수령인전화: '01012345678',
    수령인주소: '어디시 어디구', 우편번호: '12345', 품목코드: 'TST01-15', 주문수량: 1, 옵션입수: 1,
    출력번호: o.출력번호, 묶음키: ''
  }, o.덧 || {});
};
window.깔기 = function (줄들, 출고들) {
  var 저 = ZG.저장소;
  저.전체쓰기(저.키.주문, 줄들);
  저.전체쓰기(저.키.출고, 출고들 || []);
};
window.형제 = function (로젠줄들) {
  var 색인 = ZG.배송완료.색인만들기();
  return ZG.배송완료.합포장형제(로젠줄들, 색인).map(function (r) {
    return r.주문번호 + '@' + r.운송장번호;
  });
};
</script>
"""
(뿌리 / '검수' / '_합포장형제시험.html').write_text(껍데기, encoding='utf-8')

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page()
    pg.goto((뿌리 / '검수' / '_합포장형제시험.html').as_uri())

    로젠 = [{'순번': 1, '운송장번호': '44894114473', '수하인': '김은정', '박스': 1, '주문번호': 'A1'}]

    # ① 같은 출력번호 · 같은 이름 → 따라붙는다
    pg.evaluate("""() => 깔기([
      줄({id:'o1', 번호:'A1', 이름:'김은정', 출력번호:7}),
      줄({id:'o2', 번호:'A2', 이름:'김은정', 출력번호:7})
    ])""")
    r = pg.evaluate("(x) => 형제(x)", 로젠)
    본다('① 합포장 둘째 건이 같은 송장번호로 따라붙는다', r == ['A2@44894114473'], str(r))

    # ② 출력번호가 다르면 안 붙는다 (다른 송장이다)
    pg.evaluate("""() => 깔기([
      줄({id:'o1', 번호:'A1', 이름:'김은정', 출력번호:7}),
      줄({id:'o2', 번호:'A2', 이름:'김은정', 출력번호:8})
    ])""")
    r = pg.evaluate("(x) => 형제(x)", 로젠)
    본다('② 출력번호가 다르면 안 붙는다', r == [], str(r))

    # ③ 출력번호가 없으면(로젠 파일을 안 거친 새 주문) 안 붙는다
    pg.evaluate("""() => 깔기([
      줄({id:'o1', 번호:'A1', 이름:'김은정', 출력번호:7}),
      줄({id:'o2', 번호:'A2', 이름:'김은정', 출력번호:0})
    ])""")
    r = pg.evaluate("(x) => 형제(x)", 로젠)
    본다('③ 출력번호 없는 새 주문은 안 붙는다', r == [], str(r))

    # ④ 이름이 다르면 안 붙는다 (번호는 날마다 1부터 다시 센다)
    pg.evaluate("""() => 깔기([
      줄({id:'o1', 번호:'A1', 이름:'김은정', 출력번호:7}),
      줄({id:'o2', 번호:'A2', 이름:'박철수', 출력번호:7})
    ])""")
    r = pg.evaluate("(x) => 형제(x)", 로젠)
    본다('④ 이름이 다르면 안 붙는다', r == [], str(r))

    # ⑤ 이미 나간 건은 안 붙는다 (이중차감 방패)
    pg.evaluate("""() => 깔기([
      줄({id:'o1', 번호:'A1', 이름:'김은정', 출력번호:7}),
      줄({id:'o2', 번호:'A2', 이름:'김은정', 출력번호:7})
    ], [{id:'sh1', 주문id:'o2', 출처:'주문', 품목코드:'TST01-15', 수량:1}])""")
    r = pg.evaluate("(x) => 형제(x)", 로젠)
    본다('⑤ 이미 나간 건은 안 붙는다', r == [], str(r))

    # ⑥ 한 건이 여러 줄이어도 주문번호는 한 번만 붙는다
    pg.evaluate("""() => 깔기([
      줄({id:'o1', 번호:'A1', 이름:'김은정', 출력번호:7}),
      줄({id:'o2', 번호:'A2', 이름:'김은정', 출력번호:7}),
      줄({id:'o3', 번호:'A2', 이름:'김은정', 출력번호:7})
    ])""")
    r = pg.evaluate("(x) => 형제(x)", 로젠)
    본다('⑥ 여러 줄짜리 건도 한 번만 붙는다', r == ['A2@44894114473'], str(r))

    # ⑦ 파일에 이미 온 번호는 두 번 안 붙는다
    로젠2 = 로젠 + [{'순번': 2, '운송장번호': '44894114473', '수하인': '김은정', '박스': 1, '주문번호': 'A2'}]
    pg.evaluate("""() => 깔기([
      줄({id:'o1', 번호:'A1', 이름:'김은정', 출력번호:7}),
      줄({id:'o2', 번호:'A2', 이름:'김은정', 출력번호:7})
    ])""")
    r = pg.evaluate("(x) => 형제(x)", 로젠2)
    본다('⑦ 파일에 이미 온 번호는 안 붙는다', r == [], str(r))

    b.close()

for 참, 이름, 덧 in 결과:
    print(('  통과  ' if 참 else '🔴 실패 ') + 이름 + ('' if 참 else '  →  ' + 덧))
print(('전부 통과' if all(c for c, _, _ in 결과) else '🔴 실패 있음') + ' (%d건)' % len(결과))
