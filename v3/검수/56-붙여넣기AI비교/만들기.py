def 이름(): return R.choice(성) + R.choice(글자) + R.choice(글자)
def 전화(): return '010' + ''.join(R.choice('0123456789') for _ in range(8))
def 손님하나():
    도, 시들 = R.choice(시군구); 시 = R.choice(시들)
    낱 = [도, 시]
    if ('군' in 시 or 시.endswith('시')) and R.random() < 0.4: 낱.append(R.choice(길머리)[:2] + R.choice(읍면))
    길 = R.choice(길머리) + R.choice(['로', '길', '로', f'로{R.randint(1, 90)}번길', f'{R.randint(1, 30)}길'])
    번 = str(R.randint(2, 480)) + (f'-{R.randint(1, 60)}' if R.random() < 0.45 else '')
    기본 = ' '.join(낱 + [길, 번])
    k = R.random()
    상 = (f'{R.choice(아파트)}아파트 {R.randint(101, 115)}동 {R.randint(1, 25)}{R.randint(1, 4):02d}호' if k < 0.4 else
          f'{R.randint(2, 4)}층' if k < 0.55 else R.choice(['단독주택', '주택', '1호', f'{R.choice(아파트)}빌라 {R.randint(1, 4)}0{R.randint(1, 4)}호']) if k < 0.72 else '')
    참 = [R.choice(길머리)[:2] + '동'] if 상 and R.random() < 0.3 else []
    return {'출처': '가짜', '이름': 이름(), '전화': 전화(), '기본': 기본, '상세': 상, '요청': R.choice(요청들) if R.random() < 0.05 else '', '참고': 참}

if __name__ == '__main__':
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 80
    손님들 = [손님하나() for _ in range(2000)]
    칸 = {a: [] for a in (20, 30, 40, 50, 60, 70)}
    i = 0
    while any(len(v) < n for v in 칸.values()):
        m = 틀.문자하나(손님들[i % len(손님들)], 손님들); i += 1
