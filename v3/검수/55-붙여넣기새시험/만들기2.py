def 한글자틀림(t):
    자리 = [i for i, ch in enumerate(t[:-1]) if '가' <= ch <= '힣' and 중성[((ord(ch) - 0xAC00) // 28) % 21] in 바꿈]
    if not 자리: return t
    i = R.choice(자리); o = ord(t[i]) - 0xAC00
    return t[:i] + chr(0xAC00 + (o // 588) * 588 + 중성.index(바꿈[중성[(o // 28) % 21]]) * 28 + o % 28) + t[i + 1:]

def 주소쓰기(기본, 나이, 표):
    """→ (적힌 주소 글, 정답 기본) · 정답은 사람이 「여기까지 주소」라 볼 꼴(적힌 표기 그대로, 띄어쓰기는 상관없음)"""
    낱 = 기본.split(' ')
    열 = 시도열쇠(낱[0]); 몸 = 낱[1:] if 열 else 낱[:]
    번 = 몸[-1]; 길 = 몸[-2] if len(몸) >= 2 else ''; 가운데 = 몸[:-2]
    # 시·도 — 나이 들수록 생략·줄임
