    if 시도 and '실수:시도붙여씀' in 표: 낱들 = [시도 + 낱들[1]] + 낱들[2:]
    판 = 무게(('띄움', 70), ('붙임', 8 if 나이 >= 50 else 3), ('마침표', 4 if 나이 >= 60 else 0), ('쉼표', 4), ('두줄', 5))
