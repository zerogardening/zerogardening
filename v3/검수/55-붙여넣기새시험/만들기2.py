    # 시 이름에서 「시」 빼기(천안 서북구) · 구 빼기
    시군 = [i for i, t in enumerate(가운데) if re.search(r'(시|군|구)$', t)]
    if len(시군) >= 2 and 확(0.06): 가운데.pop(시군[1]); 표.append('실수:구생략')
    elif 시군 and re.fullmatch(r'[가-힣]{2}시', 가운데[시군[0]]) and 확(0.07): 가운데[시군[0]] = 가운데[시군[0]][:-1]; 표.append('실수:시빼고씀')
    # 한 글자 틀림 — 숫자 없는 낱말(사람은 「아 ○○동이겠구나」)
    후 = [i for i, t in enumerate(가운데) if len(t) >= 3 and not re.search(r'\d', t)]
    if 후 and 확(0.04 + 나이 / 1000):
        i = R.choice(후); 새 = 한글자틀림(가운데[i])
        if 새 != 가운데[i]: 가운데[i] = 새; 표.append('실수:주소한글자')
    # 번길↔길
    m = re.fullmatch(r'(.+?)(\d+)(번길|길)', 길)
    if m and 확(0.08): 길 = m.group(1) + m.group(2) + ('길' if m.group(3) == '번길' else '번길'); 표.append('실수:번길길')
    # 건물번호 구분 — 띄움·ㅡ·물결
    적번 = 번
    if '-' in 번 and 확(0.22 + 나이 / 600):
        k = 하나([' ', ' - ', 'ㅡ', '~', '.', ' -', '－', '–', ' ㅡ ', '_', '- '])
        적번 = 번.replace('-', k); 표.append('실수:번호구분')
    elif re.search(r'(동|리|가)$', 길) and 확(0.12): 적번 = 번 + '번지'
    # 길 이름 띄우기(○○로 12번길) · 통째 붙여쓰기 · 마침표 구분
    mm = re.fullmatch(r'(.+?(?:로|길))(\d+(?:번길|길))', 길)
    if mm and 확(0.08): 길 = mm.group(1) + ' ' + mm.group(2); 표.append('실수:길띄움')
    정답 = ' '.join([x for x in [시도] + 가운데 + [길, 번] if x])
