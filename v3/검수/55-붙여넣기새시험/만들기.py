def 상세쓰기(상, 나이, 표):
    if not 상: return '', ''
    m = re.search(r'(\d+)\s*동\s*(\d+)\s*호', 상)
    if m and 확(0.12):   # 동·호 순서 뒤바뀜(사람은 그대로 알아봄)
        상 = 상[:m.start()] + f'{m.group(2)}호 {m.group(1)}동' + 상[m.end():]; 표.append('실수:동호순서')
    elif m and 확(0.25):
        상 = 상[:m.start()] + 하나([f'{m.group(1)}-{m.group(2)}', f'{m.group(1)}동{m.group(2)}호', f'{m.group(1)}동 {m.group(2)}호']) + 상[m.end():]
    return 상, 상

def 정정(주글, 정답):
    """주소를 한 번 잘못 쓰고 바로 고침 — 「두동로 1129-34 아니 1192-34」 · 사람은 뒤의 것을 쓴다"""
    m = re.search(r'(\d+)(-\d+)?$', 정답)
    if not m or len(m.group(1)) < 2: return None
    a = m.group(1); 틀 = a[:-2] + a[-1] + a[-2] if a[-1] != a[-2] else str(int(a) + 1)
    앞 = 정답[:m.start()]
    return 앞 + 틀 + (m.group(2) or '') + ' ' + 하나(['아니', '아 아니고', '앗 잘못', '아니에요']) + ' ' + a + (m.group(2) or '') + 하나(['요', '입니다', '', '이에요'])

