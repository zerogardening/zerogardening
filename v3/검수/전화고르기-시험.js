/* 27칸 전화칸 세우기 — osascript -l JavaScript v3/검수/전화고르기-시험.js
   심폴 CSV 전화칸은 세 토막('XX-XXXX-XXXX')을 이어 보낸다. 안 채운 칸은 '02--' 로 온다.
   로젠은 '이름＋연락처＋주소' 가 같은 줄만 한 송장으로 묶는다 — 줄마다 같은 값이어야 한다. */
var C = { 수령인: 13, 수령지전화: 16, 전화번호: 17, 핸드폰: 18, 주소: 15 };
var 글 = function (v) { return String(v == null ? '' : v); };
var 숫자만 = function (v) { return 글(v).replace(/\D/g, ''); };
var 쓸만한전화 = function (v) { return 숫자만(v).length >= 9; };

function 전화세우기(o) {
  var 좋은 = [C.핸드폰, C.전화번호, C.수령지전화]
    .map(function (i) { return 글(o[i]).trim(); }).filter(쓸만한전화)[0] || '';
  [C.수령지전화, C.전화번호, C.핸드폰].forEach(function (i) {
    if (!쓸만한전화(o[i])) o[i] = (i === C.전화번호) ? '' : 좋은;
  });
  return o;
}

function 줄(핸드폰, 전화번호, 수령지전화) {
  var o = new Array(27).fill('');
  o[C.수령인] = '홍길동'; o[C.주소] = '서울 강남구 1';
  o[C.핸드폰] = 핸드폰; o[C.전화번호] = 전화번호; o[C.수령지전화] = 수령지전화;
  return o;
}
function 연락처키(o) { return [o[C.수령인], o[C.수령지전화], o[C.전화번호], o[C.핸드폰], o[C.주소]].join('|'); }

/* ① 심폴 두 품목 — 핸드폰이 '02--', 진짜 번호는 비상전화(전화번호 칸)에 있다 */
var a = 전화세우기(줄('02--', '010-1234-5678', ''));
var b = 전화세우기(줄('02--', '010-1234-5678', ''));
if (a[C.핸드폰] !== '010-1234-5678') throw new Error('걸림: 핸드폰 칸에 번호를 못 세웠다');
if (a[C.수령지전화] !== '010-1234-5678') throw new Error('걸림: 수령지전화 칸이 비었다 — 로젠이 못 묶는다');
if (연락처키(a) !== 연락처키(b)) throw new Error('걸림: 두 줄의 연락처가 달라 송장이 갈린다');

/* ② 멀쩡한 카페24 줄은 한 글자도 안 건드린다 */
var c = 전화세우기(줄('010-1111-2222', '02-333-4444', '031-555-6666'));
if (c[C.핸드폰] !== '010-1111-2222' || c[C.전화번호] !== '02-333-4444' || c[C.수령지전화] !== '031-555-6666') {
  throw new Error('걸림: 멀쩡한 번호를 건드렸다');
}

/* ③ 전부 빈 칸이면 빈칸 — '02--' 를 송장에 찍지 않는다 */
var d = 전화세우기(줄('02--', '031--', '--'));
if (d[C.핸드폰] !== '' || d[C.전화번호] !== '' || d[C.수령지전화] !== '') throw new Error('걸림: 토막난 번호가 남았다');

/* ④ 서울 9자리도 통과 · 보조칸(전화번호)은 채우지 않는다 */
var e = 전화세우기(줄('02--', '', '02-333-4444'));
if (e[C.핸드폰] !== '02-333-4444') throw new Error('걸림: 서울 9자리를 못 썼다');
if (e[C.전화번호] !== '') throw new Error('걸림: 보조칸까지 채웠다');

console.log('전화세우기 4묶음 통과');

/* ══ 그룹키 — 우편번호가 없어도 묶여야 한다 ══
   안 묶이면 여럿=false 라 상품명 끝 '/' 가 안 붙고, 로젠이 품목마다 송장을 따로 뽑는다
   (합포장 신호가 '/' 다 — 10단계 설계 250행) */
var 이름키 = function (v) { return 글(v).normalize('NFC').replace(/\s/g, ''); };
var 주소압축 = function (v) { return 글(v).normalize('NFC').replace(/[\s-]/g, ''); };
C.우편번호 = 14;

function 그룹키(o, 주문번호, 원본코드) {
  var 이 = 이름키(o[C.수령인]), 우 = 숫자만(o[C.우편번호]);
  if (!우) 우 = 주소압축(o[C.주소]) && '주소#' + 주소압축(o[C.주소]);
  if (!이 || !우) return '홀로#' + 주문번호 + '#' + 원본코드;
  var 전 = [o[C.핸드폰], o[C.전화번호], o[C.수령지전화]].map(숫자만).filter(쓸만한전화)[0] || '';
  return 이 + '|' + 우 + '|' + (/^050/.test(전) ? '__안심__' : 전);
}

function 심폴줄(우편, 상품코드) {
  var o = 전화세우기(줄('02--', '010-1234-5678', ''));
  o[C.우편번호] = 우편; o[C.주소] = '서울 강남구 테헤란로 1';
  return { o: o, 코드: 상품코드 };
}

/* ⑤ 우편번호가 비어도 같은 사람이면 한 묶음 */
var x = 심폴줄('', 'AAA'), y = 심폴줄('', 'BBB');
var kx = 그룹키(x.o, '…840A', x.코드), ky = 그룹키(y.o, '…840B', y.코드);
if (kx !== ky) throw new Error('걸림: 우편번호가 없다고 갈렸다 — / 가 안 붙어 송장이 따로 뽑힌다');
if (kx.indexOf('홀로') === 0) throw new Error('걸림: 홀로로 빠졌다');

/* ⑥ 우편번호가 있으면 예전 그대로 (주소는 안 본다) */
var p = 심폴줄('06234', 'AAA'), q = 심폴줄('06234', 'BBB');
q.o[C.주소] = '서울 강남구  테헤란로 1';                    // 표기가 흔들려도 상관없다
if (그룹키(p.o, '1', 'AAA') !== 그룹키(q.o, '2', 'BBB')) throw new Error('걸림: 우편번호가 같은데 갈렸다');
if (그룹키(p.o, '1', 'AAA').indexOf('주소#') >= 0) throw new Error('걸림: 우편번호가 있는데 주소로 묶었다');

/* ⑦ 이름·우편·주소가 다 없으면 홀로 */
var z = 심폴줄('', 'CCC'); z.o[C.주소] = '';
if (그룹키(z.o, 'N1', 'CCC').indexOf('홀로#') !== 0) throw new Error('걸림: 홀로로 안 빠졌다');

console.log('그룹키 3묶음 통과');
