#!/usr/bin/env python3
"""깨진 사진 막기 시험 (10/24 바르젤라 PAB01-0 1.jpg 사진 빠짐).

    python3 통합관리/v3/검수/37-그림검사/그림검사-시험.py

① 상세렌더.py — 사진 경로가 깨지는 자리(사본 폴더)에서 그리면 jpg 를 안 쓰고 끝값 2
② 상세렌더.py — 원본 자리에서 그리면 jpg 가 나온다(사진 칸 참)
③ 상세그림검사.py — 깨진 1.jpg(10/23 뽑힌 것) 는 끝값 1 · 🔴 1.jpg
④ 상세그림검사.py — 10/20 판 6장은 끝값 0
⑤ 지시함.그림검사 — 다른 갈래·없는 폴더는 '' (막지 않음)
원본 파일은 안 건드린다(사본·임시 폴더만). 실서버·카페24 안 닿음.
"""
import shutil, subprocess, sys, tempfile
from pathlib import Path

제로 = Path(__file__).resolve().parents[4]
렌더 = 제로 / '상품' / '_도구' / '상세렌더.py'
검사 = 제로 / '상품' / '_도구' / '상세그림검사.py'
품목 = 제로 / '상품' / '품목' / '이토작약-바르젤라'
깨진1 = Path.home() / 'zg-AI창' / '미리' / '0AI-1792683742235-vni4' / '후-1.jpg'   # 10/23 00:42 적용된 그림과 md5 같음
옛1 = Path.home() / 'zg-AI창' / '되돌림' / '0AI-1792683742235-vni4' / '발행-1.jpg'   # 10/20 판(카페24와 같음)
sys.path.insert(0, str(제로 / '통합관리' / '도구'))

통과 = 전체 = 0


def 본다(이름, 맞나, 덧=''):
    global 통과, 전체
    전체 += 1; 통과 += bool(맞나)
    print(('  ✅ ' if 맞나 else '  ❌ ') + 이름 + (' — ' + 덧 if 덧 and not 맞나 else ''))


def 돌려(*a):
    r = subprocess.run(['python3', *map(str, a)], capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr


with tempfile.TemporaryDirectory() as t:
    t = Path(t)
    # ① 사본 자리 — ../사진/2.jpg 가 없다
    사본 = t / '사본' / '그림.html'
    사본.parent.mkdir()
    shutil.copy2(품목 / '발행이미지' / '제작.html', 사본)
    끝, 말 = 돌려(렌더, 사본, 사본.parent, '--구역', '1')
    본다('① 사본에서 그리면 끝값 2', 끝 == 2, '%d %s' % (끝, 말[-200:]))
    본다('① 1.jpg 안 씀', not (사본.parent / '1.jpg').exists())
    본다('① ❌ 사진이 안 불러짐 줄', '사진이 안 불러짐' in 말 and '../사진/2.jpg' in 말, 말[-200:])
    # ② 원본 자리 — 낼 곳만 임시로
    낼 = t / '낼'
    끝, 말 = 돌려(렌더, 품목 / '발행이미지' / '제작.html', 낼, '--구역', '1')
    본다('② 원본 자리에서 그리면 1.jpg 나옴', 끝 in (0, 1) and (낼 / '1.jpg').exists(), '%d %s' % (끝, 말[-200:]))
    # ③·④ 검사 — 같은 제작.html, jpg 만 바꿔 끼움
    for 이름, 첫장, 기대 in (('③ 깨진 1.jpg', 깨진1, 1), ('④ 10월20일 판', 옛1, 0), ('④′ ②에서 새로 뽑은 1.jpg', 낼 / '1.jpg', 0)):
        판 = t / 이름.replace('/', '_')
        판.mkdir()
        for i in '23456':
            shutil.copy2(품목 / '발행이미지' / f'{i}.jpg', 판 / f'{i}.jpg')
        if 첫장.exists():
            shutil.copy2(첫장, 판 / '1.jpg')
        끝, 말 = 돌려(검사, '이토작약-바르젤라', '--그림', 판)
        본다(f'{이름} → 끝값 {기대}', 끝 == 기대, '%d %s' % (끝, 말[-200:]))
        if 기대:
            본다(f'{이름} → 🔴 1.jpg 사진 칸 빔', '🔴 1.jpg 사진 칸 빔' in 말, 말[-200:])

import 지시함                                                   # noqa: E402
본다('⑤ 다른 갈래는 검사 안 함', 지시함.그림검사({'갈래': '마켓품절', '폴더': '이토작약-바르젤라'}) == '')
본다('⑤ 없는 폴더는 막지 않음', 지시함.그림검사({'갈래': '상세페이지갱신', '폴더': '없는-폴더-시험'}) == '')
print('그림검사 시험 %d/%d' % (통과, 전체))
sys.exit(0 if 통과 == 전체 else 1)
