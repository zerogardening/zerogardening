/* 오프라인 단위 시험 — 심폴에 접속하지 않는다. `bun 송장칸-시험.ts`
   Deno.serve 를 빈 함수로 막아 index.ts 를 불러오기만 한다 */
(globalThis as any).Deno = { serve() {}, env: { get: () => "" } };
const { 껍데기벗기기, 송장칸판정 } = await import("../../../도구/edge-심폴발송/index.ts");

let 틀림 = 0;
const 같나 = (이름: string, 얻음: unknown, 기대: unknown) => {
  const ok = JSON.stringify(얻음) === JSON.stringify(기대);
  if (!ok) 틀림++;
  console.log((ok ? "통과 " : "틀림 ") + 이름 + (ok ? "" : ` — 얻음 ${JSON.stringify(얻음)} / 기대 ${JSON.stringify(기대)}`));
};

같나('="" → 빈', 껍데기벗기기('=""'), "");
같나('="45392501453" → 번호', 껍데기벗기기('="45392501453"'), "45392501453");
같나("평문 그대로", 껍데기벗기기("45392501453"), "45392501453");
같나("평문 한글 그대로", 껍데기벗기기(" 배송요청 "), "배송요청");
같나('따옴표 먹힌 = → 빈', 껍데기벗기기("="), "");
같나('따옴표 먹힌 =4539 → 번호', 껍데기벗기기("=45392501453"), "45392501453");
같나("빈칸·undefined", 껍데기벗기기(undefined), "");

/* 실제 CSV 모양 — 따옴표로 싼 칸 안의 `=""…""` (CSV 규칙상 따옴표 두 개 = 하나) */
const 머리 = "주문일,상품별 송장번호,거래번호,상품코드,상품별 처리여부";
const csv = [
  머리,
  '2026-10-18,"=""""",A001,"=""005017000000081207""",배송요청',          // 안 보냄 → 보낼 수 있음
  '2026-10-18,"=""45392501453""",A002,"=""005017000000081208""",배송요청', // 이미 송장
  '2026-10-18,"=""""",A003,"=""005017000000081209""","=""배송요청"""',    // 처리여부도 껍데기
  '2026-10-18,"=""""",A004,1,배송요청',                                       // 한 거래번호 둘 —
  '2026-10-18,"=""45392501454""",A004,2,배송요청',                           //   하나라도 송장이면 막힘
  '2026-10-18,"=""""",A005,1,배송완료',                                       // 처리여부가 배송요청 아님
  '2026-10-18,=\"\",A006,1,배송요청',                                         // 따옴표 없이 온 =""
].join("\r\n") + "\r\n";
const 본 = 송장칸판정(csv);
같나("A001 안 보냄", [본.A001.송장, 본.A001.배송요청], ["", true]);
같나("A002 이미 송장", 본.A002.송장, "45392501453");
같나("A003 처리여부 껍데기", [본.A003.송장, 본.A003.배송요청], ["", true]);
같나("A004 하나라도 송장이면 막힘", 본.A004.송장, "45392501454");
같나("A005 배송요청 아님", 본.A005.배송요청, false);
같나("A006 따옴표 없는 =\"\"", [본.A006.송장, 본.A006.배송요청], ["", true]);
같나("빈 CSV", 송장칸판정(""), {});

console.log(틀림 ? `\n틀림 ${틀림}개` : "\n전부 통과");
if (틀림) (globalThis as any).process?.exit(1);
