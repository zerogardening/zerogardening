"""34단계 입금 알림 읽기 시험 — edge-입금알림 의 읽기()만 떼어 타입을 벗기고 osascript(JXA)로 돌린다(이 맥엔 deno·node 없음).
돌리기: python3 통합관리/v3/검수/46-입금알림/입금알림-시험.py"""
import json, os, re, subprocess
뿌리 = os.path.normpath(os.path.join(os.path.dirname(__file__), '../../..'))
글 = open(f'{뿌리}/도구/edge-입금알림/index.ts', encoding='utf-8').read()
함수 = re.search(r'const 규칙 = [\s\S]+?\n];\n', 글).group(0) + re.search(r'export function 읽기[\s\S]+?\n}\n', 글).group(0).replace('export ', '')
함수 = re.sub(r'\((글): string, (지금): number\)', r'(\1, \2)', 함수).replace('(s: string)', '(s)')
지금 = 1794360000000  # 2026-11-10 KST 쯤
예 = [
  ('농협 입금 (우람님 캡처)', '[Web발신]\n농협 입금30,000원\n11/10 09:29 351-****-0000-00 홍길동 잔액1,000,000원',
   {'은행': '농협', '이름': '홍길동', '금액': 30000, '시각': '2026-11-10T09:29:00+09:00'}),
  ('자동출금 — 무시', '[Web발신]\n농협11/10 05:56 351-****-0000-00 자동출금\n900원(UMS수수료)\n잔액999,100원', None),
  ('한 줄로 온 입금 · 큰 금액', '농협 입금1,234,000원 11/09 23:05 351-****-0000-00 김철수 잔액9,000,000원',
   {'은행': '농협', '이름': '김철수', '금액': 1234000, '시각': '2026-11-09T23:05:00+09:00'}),
  ('이름에 띄어쓰기(회사명)', '[Web발신]\n농협 입금52,000원\n11/10 10:01 351-****-0000-00 주식회사 초록 잔액1원',
   {'은행': '농협', '이름': '주식회사 초록', '금액': 52000, '시각': '2026-11-10T10:01:00+09:00'}),
  ('잔액 줄 없음', '[Web발신]\n농협 입금8,000원\n11/10 11:11 351-****-0000-00 박영희',
   {'은행': '농협', '이름': '박영희', '금액': 8000, '시각': '2026-11-10T11:11:00+09:00'}),
  ('1월에 받은 12월 문자 → 작년', '농협 입금10,000원\n12/31 23:59 351-****-0000-00 이민수 잔액1원',
   {'은행': '농협', '이름': '이민수', '금액': 10000, '시각': '2025-12-31T23:59:00+09:00'}, 1767225600000 + 3600e3),
  ('입금 글자만 있는 광고 — 무시', '[Web발신]\n농협 입금 이벤트 안내 11/10', None),
]
통과 = 0
for 줄 in 예:
    이름, 문자, 기대 = 줄[:3]; 때 = 줄[3] if len(줄) > 3 else 지금
    js = 함수 + f'\nJSON.stringify(읽기({json.dumps(문자, ensure_ascii=False)}, {때}))'
    결과 = subprocess.run(['osascript', '-l', 'JavaScript', '-e', js], capture_output=True, text=True).stdout.strip()
    맞 = json.loads(결과 or 'null') == 기대
    통과 += 맞; print('통과' if 맞 else '실패', 이름, 결과)
print(f'{통과}/{len(예)}')
